const PROPERTY_LIST_VIEW_TYPES = new Set(["table", "board", "timeline", "calendar", "list", "gallery", "feed", "map"]);

/**
 * A database view's words in the reader's language. They are made once for a language and its strings as
 * loaded, and made again only when either changes (a language switched to, a catalog arriving later), not on
 * each call: a view's tabs, tools and menus call this many times a render, and a value typed into a table's
 * cell drew them again with each letter, some 450 lookups each time (a third of the work, 2026-11-12).
 */
export function databaseViewLabels(): DatabaseViewLabels {
  followCatalogChanges();
  const key = `${i18next.language}\u0000${catalogChanges}`;
  if (made?.key !== key) made = { key, labels: makeDatabaseViewLabels() };
  return made.labels;
}

type DatabaseViewLabels = ReturnType<typeof makeDatabaseViewLabels>;

let made: { key: string; labels: DatabaseViewLabels } | null = null;
let catalogChanges = 0;
let following = false;

function followCatalogChanges() {
  if (following || !i18next.store) return;
  following = true;
  const changed = () => { catalogChanges += 1; };
  i18next.on("languageChanged", changed);
  i18next.on("loaded", changed);
  i18next.store.on("added", changed);
  i18next.store.on("removed", changed);
}

