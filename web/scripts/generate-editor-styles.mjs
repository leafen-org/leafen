#!/usr/bin/env node

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const editorRoot = join(webRoot, 'src', 'components', 'editor')
const outputPath = join(editorRoot, 'editorStyles.generated.module.css')
const mode = process.argv[2]
const sourceNames = [
  'EditorCanvas.module.css',
  'EditorBlocks.module.css',
  'EditorBlockSelection.module.css',
  'EditorBlockBody.module.css',
  'EditorBlockHandles.module.css',
  'EditorText.module.css',
  'EditorTabBlocks.module.css',
  'EditorRichBlocks.module.css',
  'EditorNotationBlocks.module.css',
  'EditorImageBlocks.module.css',
  'EditorMediaBlocks.module.css',
  'EditorBookmarkBlocks.module.css',
  'EditorFileBlocks.module.css',
  'EditorLayoutBlocks.module.css',
  'EditorSimpleTable.module.css',
  'EditorColumns.module.css',
  'EditorDatabaseBlocks.module.css',
  'EditorPageLinks.module.css',
  'EditorSlashMenu.module.css',
  'EditorActionsAndMarks.module.css',
  'EditorInlineMarks.module.css',
  'EditorInlineDecorations.module.css',
  'EditorSelectionToolbar.module.css',
  'EditorLinkMenu.module.css',
  'EditorInlinePickers.module.css',
]

function render() {
  const sources = sourceNames.map((name) => {
    const path = join(editorRoot, name)
    const source = readFileSync(path, 'utf8')
    if (source.length === 0 || !source.endsWith('\n')) {
      throw new Error(`${relative(webRoot, path)} must be nonempty and newline-terminated`)
    }
    return source
  })
  return `/* Code generated by web/scripts/generate-editor-styles.mjs. DO NOT EDIT. */\n${sources.join('')}`
}

function check() {
  const actual = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : ''
  if (actual !== render()) {
    throw new Error(`${relative(webRoot, outputPath)} is stale; run generate-editor-styles.mjs --write`)
  }
}

if (mode === '--check') check()
else if (mode === '--write') writeFileSync(outputPath, render())
else throw new Error('Usage: node scripts/generate-editor-styles.mjs --check|--write')
