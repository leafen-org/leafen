import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { wireOptionalTag } from './wire-field-tag.mjs'

const productRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')

function options(argv) {
  const result = {
    check: false,
    contract: resolve(productRoot, 'contracts/database-toolbar-config-wire.json'),
    goOutput: resolve(productRoot, 'internal/app/database_toolbar_config_wire.generated.go'),
    tsOutput: resolve(productRoot, 'web/src/databaseToolbarConfigWire.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') result.check = true
    else {
      const key = { '--contract': 'contract', '--go-output': 'goOutput', '--ts-output': 'tsOutput' }[argument]
      if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
      result[key] = resolve(productRoot, argv[++index])
    }
  }
  return result
}

function validate(contract) {
  if (contract?.schemaVersion !== 2 || contract?.name !== 'database-toolbar-config') {
    throw new Error('database toolbar configuration contract must use schemaVersion 2')
  }
  for (const key of ['operations', 'bounds', 'errors', 'records']) {
    if (!Array.isArray(contract[key]) || contract[key].length === 0) throw new Error(`contract requires ${key}`)
  }
  const unique = (values, label) => {
    if (new Set(values).size !== values.length) throw new Error(`${label} contains duplicates`)
  }
  unique(contract.operations.map(({ path, method }) => `${method}:${path}`), 'operations')
  unique(contract.records.map(({ goName }) => goName), 'Go records')
  unique(contract.records.map(({ tsName }) => tsName), 'TypeScript records')
  for (const record of contract.records) unique(record.fields.map(({ jsonName }) => jsonName), `${record.tsName} fields`)
}

function renderGo(contract, hash) {
  const lines = [
    '// Code generated by scripts/generate-database-toolbar-config-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${hash}`,
    '',
    'package app',
    '',
    'import "encoding/json"',
    '',
    'const (',
  ]
  for (const operation of contract.operations) {
    lines.push(`\t${operation.goName}Method = ${JSON.stringify(operation.method)}`)
    lines.push(`\t${operation.goName}Path = ${JSON.stringify(operation.path)}`)
  }
  lines.push('')
  for (const bound of contract.bounds) lines.push(`\t${bound.goName} = ${bound.value}`)
  lines.push('')
  for (const error of contract.errors) lines.push(`\t${error.goName} = ${JSON.stringify(error.value)}`)
  lines.push(')', '')
  for (const record of contract.records) {
    lines.push(`type ${record.goName} struct {`)
    for (const field of record.fields) {
      lines.push(`\t${field.goName} ${field.goType} \`json:"${field.jsonName}${wireOptionalTag(field)}"\``)
    }
    lines.push('}', '')
  }
  const formatted = spawnSync('gofmt', [], { input: `${lines.join('\n')}\n`, encoding: 'utf8' })
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
  return formatted.stdout
}

function renderTypeScript(contract, hash) {
  const lines = [
    '// Code generated by scripts/generate-database-toolbar-config-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${hash}`,
    '',
    'export const databaseToolbarConfigContract = {',
    `  schemaVersion: ${contract.schemaVersion},`,
    `  name: ${JSON.stringify(contract.name)},`,
    '} as const;',
    '',
    'export const databaseToolbarConfigOperations = {',
  ]
  for (const operation of contract.operations) {
    lines.push(`  ${operation.tsName}: { method: ${JSON.stringify(operation.method)}, path: ${JSON.stringify(operation.path)} },`)
  }
  lines.push('} as const;', '', 'export const databaseToolbarConfigBounds = {')
  for (const bound of contract.bounds) lines.push(`  ${bound.tsName}: ${bound.value},`)
  lines.push('} as const;', '', 'export const databaseToolbarConfigErrorCodes = {')
  for (const error of contract.errors) lines.push(`  ${error.tsName}: ${JSON.stringify(error.value)},`)
  lines.push('} as const;', '')
  for (const record of contract.records) {
    lines.push(`export type ${record.tsName} = {`)
    for (const field of record.fields) lines.push(`  ${field.jsonName}${field.optional ? '?' : ''}: ${field.tsType};`)
    lines.push('};', '')
  }
  return `${lines.join('\n').trimEnd()}\n`
}

function emit(path, expected, check) {
  if (check) {
    let actual = ''
    try { actual = readFileSync(path, 'utf8') } catch (error) { if (error?.code !== 'ENOENT') throw error }
    if (actual !== expected) {
      process.stderr.write(`stale generated output: ${relative(productRoot, path)}\n`)
      process.exitCode = 1
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, expected)
}

try {
  const resolved = options(process.argv.slice(2))
  const contractSource = readFileSync(resolved.contract, 'utf8')
  const contract = JSON.parse(contractSource)
  validate(contract)
  const hash = createHash('sha256').update(contractSource).digest('hex')
  emit(resolved.goOutput, renderGo(contract, hash), resolved.check)
  emit(resolved.tsOutput, renderTypeScript(contract, hash), resolved.check)
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
}
