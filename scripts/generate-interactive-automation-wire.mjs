const scriptsRoot = dirname(fileURLToPath(import.meta.url))
const productRoot = resolve(scriptsRoot, '..')

function options(argv) {
  const result = {
    check: false,
    contract: resolve(productRoot, 'contracts/interactive-automation-wire.json'),
    goOutput: resolve(productRoot, 'internal/app/interactive_automation_wire.generated.go'),
    tsOutput: resolve(productRoot, 'web/src/interactiveAutomationWire.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') result.check = true
    else {
      const key = { '--contract': 'contract', '--go-output': 'goOutput', '--ts-output': 'tsOutput' }[argument]
      if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
      result[key] = resolve(productRoot, argv[++index])
    }
  }
  return result
}

function assertContract(contract) {
  if (contract?.schemaVersion !== 1 || contract?.name !== 'interactive-automation') {
    throw new Error('interactive automation contract must use schemaVersion 1')
  }
  for (const key of ['documentBytes', 'resultBytes', 'targetRows', 'identifierRunes']) {
    if (!Number.isSafeInteger(contract.bounds?.[key]) || contract.bounds[key] < 1) throw new Error(`invalid bound: ${key}`)
  }
  if (!Array.isArray(contract.actionTypes) || new Set(contract.actionTypes).size !== contract.actionTypes.length) {
    throw new Error('actionTypes must be a unique list')
  }
  for (const key of ['notificationRecipientKinds', 'formulaContextNames']) {
    if (!Array.isArray(contract[key]) || !contract[key].length || new Set(contract[key]).size !== contract[key].length
      || contract[key].some(value => typeof value !== 'string' || !/^[a-z][A-Za-z_]+$/u.test(value))) {
      throw new Error(`${key} must be a unique nonempty list`)
    }
  }
  if (!Array.isArray(contract.blockInsertionPositions) || !contract.blockInsertionPositions.length
    || new Set(contract.blockInsertionPositions).size !== contract.blockInsertionPositions.length
    || contract.blockInsertionPositions.some(value => typeof value !== 'string' || !/^[a-z]+(?:_[a-z]+)+$/u.test(value))) {
    throw new Error('blockInsertionPositions must be a unique nonempty list')
  }
  // Three runs and the read of a database an action may target.
  if (!Array.isArray(contract.operations) || contract.operations.length !== 4
    || contract.operations.filter((operation) => operation.method === 'GET').length !== 1) {
    throw new Error('interactive automation requires three run routes and one target read')
  }
  if (new Set(contract.operations.map((operation) => operation.name)).size !== contract.operations.length
    || contract.operations.some((operation) => !/^[a-z][A-Za-z]+$/u.test(operation.name)
      || !['POST', 'GET'].includes(operation.method) || typeof operation.path !== 'string')) {
    throw new Error('interactive automation operations are invalid')
  }
  for (const key of ['invalid', 'notFound', 'unsupported', 'conflict', 'storageUnavailable', 'databaseBusy', 'unavailable']) {
    if (!/^LEAFEN_[A-Z_]+$/u.test(contract.errors?.[key] ?? '')) throw new Error(`invalid error: ${key}`)
  }
}

