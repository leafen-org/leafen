import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { wireOptionalTag } from './wire-field-tag.mjs'

const scriptsRoot = dirname(fileURLToPath(import.meta.url))
const productRoot = resolve(scriptsRoot, '..')

function parseArgs(argv) {
  const options = {
    check: false,
    contract: resolve(productRoot, 'contracts/notion-admin-token-wire.json'),
    goOutput: resolve(productRoot, 'internal/app/notion_admin_token_wire.generated.go'),
    tsOutput: resolve(productRoot, 'web/src/notionAdminTokenWire.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') {
      options.check = true
      continue
    }
    const key = { '--contract': 'contract', '--go-output': 'goOutput', '--ts-output': 'tsOutput' }[argument]
    if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
    options[key] = resolve(productRoot, argv[index + 1])
    index += 1
  }
  return options
}

function assertContract(contract) {
  if (contract?.schemaVersion !== 1 || contract?.name !== 'notion-admin-token') {
    throw new Error('notion admin token contract must use schemaVersion 1')
  }
  for (const key of ['operations', 'bounds', 'strings', 'errors', 'enums', 'records']) {
    if (!Array.isArray(contract[key]) || contract[key].length === 0) throw new Error(`contract requires ${key}`)
  }
  const unique = (values, label) => {
    if (new Set(values).size !== values.length) throw new Error(`${label} contains duplicates`)
  }
  unique(contract.operations.map((entry) => entry.goName), 'Go operations')
  unique(contract.records.map((entry) => entry.goName), 'Go records')
  unique(contract.records.map((entry) => entry.tsName), 'TypeScript records')
  for (const record of contract.records) unique(record.fields.map((field) => field.jsonName), `${record.tsName} fields`)
}

function renderGo(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-notion-admin-token-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`, '', 'package app', '', 'const (',
  ]
  for (const entry of contract.operations) {
    lines.push(`\t${entry.goName}Method = ${JSON.stringify(entry.method)}`)
    lines.push(`\t${entry.goName}Path = ${JSON.stringify(entry.path)}`)
  }
  lines.push('')
  for (const entry of contract.bounds) lines.push(`\t${entry.goName} = ${entry.value}`)
  lines.push('')
  for (const entry of contract.strings) lines.push(`\t${entry.goName} = ${JSON.stringify(entry.value)}`)
  lines.push('')
  for (const entry of contract.errors) lines.push(`\t${entry.goName} = ${JSON.stringify(entry.value)}`)
  for (const enumeration of contract.enums) {
    lines.push('')
    for (const entry of enumeration.values) lines.push(`\t${entry.goName} = ${JSON.stringify(entry.value)}`)
  }
  lines.push(')', '')
  const capabilityEnum = contract.enums.find(({ tsName }) => tsName === 'NotionAdminCapability')
  if (!capabilityEnum) throw new Error('NotionAdminCapability enum is required')
  lines.push('var notionAdminCapabilitySet = map[string]struct{}{')
  for (const entry of capabilityEnum.values) lines.push(`\t${entry.goName}: {},`)
  lines.push('}', '')
  for (const record of contract.records) {
    lines.push(`type ${record.goName} struct {`)
    for (const field of record.fields) {
      lines.push(`\t${field.goName} ${field.goType} \`json:"${field.jsonName}${wireOptionalTag(field)}"\``)
    }
    lines.push('}', '')
  }
  const formatted = spawnSync('gofmt', [], { input: `${lines.join('\n')}\n`, encoding: 'utf8' })
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
  return formatted.stdout
}

function renderTypeScript(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-notion-admin-token-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`, '', 'export const notionAdminTokenOperations = {',
  ]
  for (const entry of contract.operations) {
    lines.push(`  ${entry.tsName}: { method: ${JSON.stringify(entry.method)}, path: ${JSON.stringify(entry.path)} },`)
  }
  lines.push('} as const;', '', 'export const notionAdminTokenBounds = {')
  for (const entry of contract.bounds) lines.push(`  ${entry.tsName}: ${entry.value},`)
  lines.push('} as const;', '', 'export const notionAdminTokenStrings = {')
  for (const entry of contract.strings) lines.push(`  ${entry.tsName}: ${JSON.stringify(entry.value)},`)
  lines.push('} as const;', '', 'export const notionAdminTokenErrorCodes = {')
  for (const entry of contract.errors) lines.push(`  ${entry.tsName}: ${JSON.stringify(entry.value)},`)
  lines.push('} as const;', '')
  for (const enumeration of contract.enums) {
    lines.push(`export const ${enumeration.tsValuesName} = {`)
    for (const entry of enumeration.values) lines.push(`  ${entry.tsName}: ${JSON.stringify(entry.value)},`)
    lines.push('} as const;')
    lines.push(`export type ${enumeration.tsName} = typeof ${enumeration.tsValuesName}[keyof typeof ${enumeration.tsValuesName}];`, '')
  }
  for (const record of contract.records) {
    lines.push(`export type ${record.tsName} = {`)
    for (const field of record.fields) lines.push(`  ${field.jsonName}${field.optional ? '?' : ''}: ${field.tsType};`)
    lines.push('};', '')
  }
  while (lines.at(-1) === '') lines.pop()
  return `${lines.join('\n')}\n`
}

function checkOrWrite(path, expected, check) {
  if (check) {
    let actual = ''
    try { actual = readFileSync(path, 'utf8') } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
    if (actual !== expected) {
      process.stderr.write(`stale generated output: ${relative(productRoot, path)}\n`)
      process.exitCode = 1
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, expected)
}

try {
  const options = parseArgs(process.argv.slice(2))
  const contractSource = readFileSync(options.contract, 'utf8')
  const contract = JSON.parse(contractSource)
  assertContract(contract)
  const digest = createHash('sha256').update(contractSource).digest('hex')
  checkOrWrite(options.goOutput, renderGo(contract, digest), options.check)
  checkOrWrite(options.tsOutput, renderTypeScript(contract, digest), options.check)
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
}
