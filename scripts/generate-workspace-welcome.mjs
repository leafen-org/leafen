// Writes the welcome page a workspace that starts empty opens on, in each
// language the catalog has it, for the server, which makes that page however
// the workspace is made (the web app, the API, a CLI); and the name a first
// workspace takes after its person, which the server gives one it makes
// itself (a first run done in an agent's conversation, workspace_initial.go).
import { spawnSync } from 'node:child_process'
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const productRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const locales = resolve(productRoot, 'web/src/locales')
const output = resolve(productRoot, 'internal/app/workspace_welcome_text.generated.go')
const check = process.argv.includes('--check')

const read = (language, namespace) => {
  const file = resolve(locales, language, `${namespace}.json`)
  return existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : {}
}

function welcomePage(language) {
  const page = read(language, 'common').generated?.welcomePage
  // A language whose page is not all translated yet (a title alone) has none:
  // the server gives it the page in its own language.
  const parts = ['title', 'intro', 'basicsHeading', 'slash', 'pages', 'databases', 'together', 'importHeading', 'import', 'agentsHeading', 'agents']
  if (!page || parts.some((part) => typeof page[part] !== 'string')) return null
  const settings = read(language, 'workspaceSettingsDialog')
  const english = read('en', 'workspaceSettingsDialog')
  const place = {
    settings: read(language, 'sidebar').settings ?? read('en', 'sidebar').settings,
    workspace: settings.navWorkspaceGroup ?? english.navWorkspaceGroup,
    import: settings.navImports ?? english.navImports,
    features: settings.navFeaturesGroup ?? english.navFeaturesGroup,
    agents: settings.navAiConnections ?? english.navAiConnections,
    // The workspace menu's row, one press from the sidebar (2026-11-12).
    connectAgent: read(language, 'sidebar').connectAgent ?? read('en', 'sidebar').connectAgent,
  }
  const fill = (text) => text.replace(/\{\{(\w+)\}\}/gu, (_, key) => place[key])
  return {
    title: page.title,
    markdown: [
      page.intro, '',
      `## ${page.basicsHeading}`,
      ...['slash', 'pages', 'databases', 'together'].map((key) => `- ${page[key]}`), '',
      `## ${page.importHeading}`, fill(page.import), '',
      `## ${page.agentsHeading}`, fill(page.agents),
    ].join('\n'),
  }
}

const entries = readdirSync(locales, { withFileTypes: true })
  .filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort()
  .map((language) => [language, welcomePage(language)]).filter(([, page]) => page)
const names = entries.map(([language]) => [language, read(language, 'common').generated?.workspaceName])
  .filter(([, name]) => typeof name === 'string' && name.includes('{{name}}'))
const source = `// Code generated by scripts/generate-workspace-welcome.mjs. DO NOT EDIT.

package app

var workspaceWelcomeTexts = map[string]workspaceWelcomePageInput{
${entries.map(([language, page]) => `\t${JSON.stringify(language)}: {\n\t\tTitle:    ${JSON.stringify(page.title)},\n\t\tMarkdown: ${JSON.stringify(page.markdown)},\n\t},`).join('\n')}
}

// workspaceFirstNames name a first workspace after its person ({{name}}).
var workspaceFirstNames = map[string]string{
${names.map(([language, name]) => `\t${JSON.stringify(language)}: ${JSON.stringify(name)},`).join('\n')}
}
`
// gofmt lines the names up by the longest language key (zh-Hans), so the
// file is what gofmt makes of it, whichever languages the catalog has.
const formatted = spawnSync('gofmt', [], { input: source, encoding: 'utf8' })
if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
const generated = formatted.stdout
if (check) {
  if (!existsSync(output) || readFileSync(output, 'utf8') !== generated) {
    console.error('stale generated output: internal/app/workspace_welcome_text.generated.go (run node scripts/generate-workspace-welcome.mjs)')
    process.exit(1)
  }
} else writeFileSync(output, generated)
