// Writes the names of the screens an agent's texts send its person to, in
// each language the web app's catalogs have them, for the server
// (mcp_screen_names.go): an agent tells a person where to press in the words
// of that person's own screen. A language without a name shows the English.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const productRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const locales = resolve(productRoot, 'web/src/locales')
const output = resolve(productRoot, 'internal/app/mcp_screen_names.generated.go')
const check = process.argv.includes('--check')

// Each screen name, by the catalog entry the screen draws it from.
const screens = {
  connectAgent: ['sidebar', 'connectAgent'],
  settings: ['sidebar', 'settings'],
  preferences: ['workspaceSettingsDialog', 'preferencesTitle'],
  // Preferences' last section, which holds the row below.
  install: ['desktopBackground', 'finishSkippedSection'],
  finishSkipped: ['desktopBackground', 'finishSkipped'],
  features: ['workspaceSettingsDialog', 'navFeaturesGroup'],
  agents: ['workspaceSettingsDialog', 'navAiConnections'],
  agentsMore: ['workspaceSettingsDialog', 'agents.more'],
  agentsOtherComputer: ['workspaceSettingsDialog', 'agents.otherComputer'],
  agentsConnected: ['workspaceSettingsDialog', 'agents.connectedTitle'],
  connections: ['workspaceSettingsDialog', 'navIntegrations'],
  workspace: ['workspaceSettingsDialog', 'navWorkspaceGroup'],
  general: ['workspaceSettingsDialog', 'navGeneral'],
  import: ['workspaceSettingsDialog', 'navImports'],
  workspaceMove: ['workspaceSettingsDialog', 'move.title'],
  workspaceMoveOut: ['workspaceSettingsDialog', 'move.outTitle'],
  workspaceMoveIn: ['workspaceSettingsDialog', 'move.inTitle'],
  server: ['workspaceSettingsDialog', 'navServerGroup'],
  serverBackups: ['serverConsole', 'nav.data'],
  serverEmail: ['serverConsole', 'nav.email'],
  serverSignIn: ['serverConsole', 'nav.providers'],
  serverMap: ['serverConsole', 'nav.map'],
  serverApps: ['serverConsole', 'nav.apps'],
  serverUsers: ['serverConsole', 'nav.users'],
  accountSecurity: ['workspaceSettingsDialog', 'navAccountSecurity'],
  serverStandby: ['serverConsole', 'nav.standby'],
  serverRemoteAccess: ['serverConsole', 'nav.tunnel'],
  serverRestore: ['serverConsole', 'nav.restore'],
  serverMove: ['serverConsole', 'serverMove.title'],
  serverMoveIn: ['serverConsole', 'serverMove.inOpen'],
  standbyAdd: ['serverConsole', 'standby.add'],
  standbyJoin: ['serverConsole', 'standby.joinTitle'],
  standbyTakeOver: ['serverConsole', 'standby.takeOver'],
  standbyKeepApart: ['serverConsole', 'replication.keepApart'],
  // The sign-in screen's way in with a signed-in device's code, and its
  // agent's approval right under it.
  signInEnterCode: ['authGate', 'enterCode'],
  signInAgent: ['authGate', 'agentSignIn'],
  addDevice: ['workspaceSettingsDialog', 'addDevice'],
}

const catalogs = new Map()
const read = (language, namespace) => {
  const key = `${language}/${namespace}`
  if (!catalogs.has(key)) {
    const file = resolve(locales, language, `${namespace}.json`)
    catalogs.set(key, existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : {})
  }
  return catalogs.get(key)
}
const entry = (language, [namespace, path]) => {
  const value = path.split('.').reduce((at, part) => (at && typeof at === 'object' ? at[part] : undefined), read(language, namespace))
  return typeof value === 'string' && value.trim() ? value.trim() : ''
}

const languages = readdirSync(locales, { withFileTypes: true }).filter((item) => item.isDirectory()).map((item) => item.name).sort()
const missing = Object.entries(screens).filter(([, source]) => !entry('en', source)).map(([name]) => name)
if (missing.length) {
  console.error(`mcp screen names missing in English: ${missing.join(', ')}`)
  process.exit(1)
}
const rows = languages.map((language) => [language, Object.entries(screens).map(([name, source]) => [name, entry(language, source)]).filter(([, label]) => label)])
  .filter(([, names]) => names.length).map(([language, names]) => {
  // The values line up as gofmt lines them up.
  const width = Math.max(...names.map(([name]) => JSON.stringify(name).length)) + 1
  const line = ([name, label]) => `\t\t${`${JSON.stringify(name)}:`.padEnd(width)} ${JSON.stringify(label)},`
  return `\t${JSON.stringify(language)}: {\n${names.map(line).join('\n')}\n\t},`
})
const generated = `// Code generated by scripts/generate-mcp-screen-names.mjs. DO NOT EDIT.

package app

var mcpScreenNames = map[string]map[string]string{
${rows.join('\n')}
}
`
if (check) {
  if (!existsSync(output) || readFileSync(output, 'utf8') !== generated) {
    console.error('stale generated output: internal/app/mcp_screen_names.generated.go (run node scripts/generate-mcp-screen-names.mjs)')
    process.exit(1)
  }
} else writeFileSync(output, generated)
