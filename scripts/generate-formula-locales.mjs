import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

// Writes the date words and layouts formulas use for the languages both Leafen
// and Notion show besides English and Korean, from moment.js's locale files:
// Notion's formulas write dates with moment.js, as its Korean screen showed
// (formulaLocales.ts keeps English and Korean by hand). moment.js is not a
// dependency; give the folder of an unpacked moment 2.30.1 package:
//
//   node scripts/generate-formula-locales.mjs /path/to/moment [--check]

const productRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const output = resolve(productRoot, 'web/src/components/database/formulaLocales.generated.ts')
const momentRoot = process.argv.slice(2).find((argument) => !argument.startsWith('--'))
const check = process.argv.includes('--check')
if (!momentRoot) throw new Error('give the folder of an unpacked moment 2.30.1 package')
const version = JSON.parse(readFileSync(join(momentRoot, 'package.json'), 'utf8')).version
if (version !== '2.30.1') throw new Error(`moment ${version} is not 2.30.1`)

// Leafen's language, and the moment.js locale that writes it.
const languages = [
  ['ja', 'ja'], ['fr', 'fr'], ['de', 'de'], ['es', 'es'], ['pt-BR', 'pt-br'], ['zh-Hans', 'zh-cn'], ['zh-Hant', 'zh-tw'],
  ['nl', 'nl'], ['nb', 'nb'], ['sv', 'sv'], ['da', 'da'], ['fi', 'fi'], ['vi', 'vi'], ['th', 'th'], ['id', 'id'],
  ['ar', 'ar'], ['he', 'he'], ['it', 'it'],
]
const layouts = ['LT', 'LTS', 'L', 'LL', 'LLL', 'LLLL', 'l', 'll', 'lll', 'llll']

const require = createRequire(import.meta.url)
const moment = require(join(momentRoot, 'moment.js'))
for (const [, name] of languages) require(join(momentRoot, 'locale', `${name}.js`))

function localeTable(name) {
  const data = moment.localeData(name)
  const day = (month, date) => moment.utc([2026, month, date, 12]).locale(name)
  const same = (list, inFormat, what) => {
    if (JSON.stringify(list) !== JSON.stringify(inFormat)) throw new Error(`${name} writes ${what} differently in a layout`)
    return list
  }
  const months = same(
    Array.from({ length: 12 }, (_, month) => data.months(day(month, 1), 'MMMM')),
    Array.from({ length: 12 }, (_, month) => data.months(day(month, 1), 'D MMMM')), 'months')
  const monthsShort = same(
    Array.from({ length: 12 }, (_, month) => data.monthsShort(day(month, 1), 'MMM')),
    Array.from({ length: 12 }, (_, month) => data.monthsShort(day(month, 1), 'D MMM')), 'short months')
  // 2026-01-04 is a Sunday.
  const weekday = (index, token) => data[token](day(0, 4 + index), token === 'weekdays' ? 'dddd' : undefined)
  const meridiem = []
  for (let minute = 0; minute < 24 * 60; minute += 1) {
    const upper = data.meridiem(Math.floor(minute / 60), minute % 60, false)
    const lower = data.meridiem(Math.floor(minute / 60), minute % 60, true)
    const last = meridiem.at(-1)
    if (!last || last[1] !== upper || last[2] !== lower) meridiem.push([minute, upper, lower])
  }
  return {
    months,
    monthsShort,
    weekdays: Array.from({ length: 7 }, (_, index) => weekday(index, 'weekdays')),
    weekdaysShort: Array.from({ length: 7 }, (_, index) => weekday(index, 'weekdaysShort')),
    weekdaysMin: Array.from({ length: 7 }, (_, index) => weekday(index, 'weekdaysMin')),
    meridiem,
    ordinals: Array.from({ length: 31 }, (_, index) => String(data.ordinal(index + 1, 'D'))),
    layouts: Object.fromEntries(layouts.map((token) => [token, data.longDateFormat(token)])),
  }
}

const tables = Object.fromEntries(languages.map(([language, name]) => [language, localeTable(name)]))
const text = `// Code generated by scripts/generate-formula-locales.mjs from moment.js ${version} locale files
// (MIT License, Copyright (c) JS Foundation and other contributors). DO NOT EDIT.

export type GeneratedFormulaLocale = {
  months: readonly string[];
  monthsShort: readonly string[];
  weekdays: readonly string[];
  weekdaysShort: readonly string[];
  weekdaysMin: readonly string[];
  // The words for the time of day from each minute of the day on:
  // [minute, upper case, lower case].
  meridiem: readonly (readonly [number, string, string])[];
  // The days of the month as ordinals, from the 1st.
  ordinals: readonly string[];
  layouts: Readonly<Record<${layouts.map((token) => JSON.stringify(token)).join(' | ')}, string>>;
};

export const GENERATED_FORMULA_LOCALES: Readonly<Record<string, GeneratedFormulaLocale>> = ${JSON.stringify(tables, null, 2)};
`
if (check) {
  if (readFileSync(output, 'utf8') !== text) {
    console.error(`${output} is out of date; run node scripts/generate-formula-locales.mjs <moment folder>`)
    process.exit(1)
  }
} else {
  writeFileSync(output, text)
}
