import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { relativeSlashPath } from './source-paths.mjs'

// The icons an HTML export draws, as the web app draws them; the server
// writes the exports, so it keeps them, drawn once here. --check fails when
// the web app's icons changed and this was not run again.
//
// Each database column's kind by its icon, as Notion's export does (seen
// 2026-11-07: a 14px gray icon before each header and each row page's
// property name), as SVG (PropertyTypeIcon).
//
// Each built-in icon's glyph (BuiltInIconGlyph) and its colors in the light
// theme the export is drawn in (iconPalette.css), which the export draws
// inside the file, where Notion's loads its icon from app.notion.com:
// each glyph is what its 20 by 20 box holds in currentColor, a
// glyph cut from a disc or drawn solid naming its mask "cut" (and a solid
// one its clip "cut-in").

const scriptsRoot = dirname(fileURLToPath(import.meta.url))
const productRoot = resolve(scriptsRoot, '..')
const webRoot = resolve(productRoot, 'web')
const output = resolve(productRoot, 'internal/app/workspace_export_property_icons.generated.go')
const builtInOutput = resolve(productRoot, 'internal/app/workspace_export_builtin_icons.generated.json')

const TYPES = [
  'title', 'rich_text', 'number', 'select', 'multi_select', 'status', 'date', 'person', 'checkbox', 'url', 'email',
  'phone', 'files', 'created_time', 'last_edited_time', 'created_by', 'last_edited_by', 'relation', 'rollup',
  'formula', 'unique_id', 'button', 'location', 'verification', 'last_visited_time', 'place',
]

async function renderIcons() {
  const require = createRequire(resolve(webRoot, 'package.json'))
  const { createServer } = await import(pathToFileURL(require.resolve('vite')).href)
  const server = await createServer({
    root: webRoot,
    configFile: resolve(webRoot, 'vite.config.ts'),
    logLevel: 'error',
    appType: 'custom',
    server: { middlewareMode: true, hmr: false, watch: null },
    optimizeDeps: { noDiscovery: true, include: [] },
  })
  try {
    const { PropertyTypeIcon } = await server.ssrLoadModule('/src/components/database/PropertyTypeIcon.tsx')
    const { BuiltInIconGlyph } = await server.ssrLoadModule('/src/components/page/PageIcon.tsx')
    const { NATIVE_ICON_GLYPHS } = await server.ssrLoadModule('/src/components/page/nativeIconGlyphs.ts')
    const { NATIVE_ICONS } = await server.ssrLoadModule('/src/nativeIconCatalog.generated.ts')
    const React = require('react')
    const { renderToStaticMarkup } = require('react-dom/server')
    const properties = TYPES.map((type) => {
      const svg = renderToStaticMarkup(React.createElement(PropertyTypeIcon, { type, size: 'tiny' }))
      return [type, svg.replace(/ class="[^"]*"/g, '').replace(/ data-[a-z-]+="[^"]*"/g, '')]
    })
    const glyph = (name) => {
      const svg = renderToStaticMarkup(React.createElement(BuiltInIconGlyph, { icon: { name, color: 'gray' }, size: 20, color: 'currentColor' }))
      const inner = svg.replace(/^<svg[^>]*>(<title>[^<]*<\/title>)?/, '').replace(/<\/svg>$/, '')
      // Its mask "cut" and a solid glyph's clip, the mask's name and "-in".
      return inner.replace(/native-icon-cut-[^")-]*/g, 'cut')
    }
    const glyphs = Object.fromEntries(NATIVE_ICONS.map(([name]) => name).filter((name) => NATIVE_ICON_GLYPHS[name]).map((name) => [name, glyph(name)]))
    return { properties, builtIn: { colors: lightIconColors(), neutral: glyph(''), glyphs } }
  } finally {
    await server.close()
  }
}

// The built-in icons' colors in the light theme (iconPalette.css).
function lightIconColors() {
  const css = readFileSync(resolve(webRoot, 'src/app/iconPalette.css'), 'utf8')
  const light = css.match(/\[data-theme="light"\]\s*\{([^}]*)\}/)
  if (!light) throw new Error('iconPalette.css has no light theme block')
  const colors = Object.fromEntries([...light[1].matchAll(/--icon-c-([a-z]+):\s*(#[0-9a-f]{3,8});/g)].map((match) => [match[1], match[2]]))
  if (Object.keys(colors).length === 0) throw new Error('iconPalette.css names no light icon colors')
  return colors
}

function goFile(icons) {
  const lines = icons.map(([type, svg]) => `\t${JSON.stringify(type)}: ${JSON.stringify(svg)},`)
  const formatted = spawnSync('gofmt', [], { input: goSource(lines), encoding: 'utf8' })
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
  return formatted.stdout
}

function goSource(lines) {
  return `// Code generated by ${relativeSlashPath(productRoot, fileURLToPath(import.meta.url))}; DO NOT EDIT.

package app

// workspaceExportPropertyIcons are the web app's icons for each property
// kind, as an HTML export draws them before a column's or a property's name.
var workspaceExportPropertyIcons = map[string]string{
${lines.join('\n')}
}
`
}

function checkOrWrite(path, next, check) {
  if (check) {
    let current = ''
    try {
      current = readFileSync(path, 'utf8')
    } catch {}
    if (current !== next) {
      console.error(`${relative(productRoot, path)} is out of date: run node scripts/generate-export-property-icons.mjs`)
      process.exitCode = 1
    }
    return
  }
  writeFileSync(path, next)
}

const check = process.argv.includes('--check')
const icons = await renderIcons()
checkOrWrite(output, goFile(icons.properties), check)
checkOrWrite(builtInOutput, `${JSON.stringify(icons.builtIn, null, 1)}\n`, check)
