import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

// The code block languages and the names a fence or code element may give
// them, for the editor and the server alike (contracts/code-languages.json):
// also the name an HTML export marks each with, Prism's, as Notion's HTML
// export does (seen 2026-11-14: "javascript" as "jsx", "c++" as "cpp"; its
// own name where none is listed), and the ones it marks with none, as plain
// text ("ascii art").

const scriptsRoot = dirname(fileURLToPath(import.meta.url))
const productRoot = resolve(scriptsRoot, '..')

function parseArgs(argv) {
  const options = {
    check: false,
    contract: resolve(productRoot, 'contracts/code-languages.json'),
    goOutput: resolve(productRoot, 'internal/app/code_languages.generated.go'),
    tsOutput: resolve(productRoot, 'web/src/codeLanguages.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') {
      options.check = true
      continue
    }
    const key = {
      '--contract': 'contract',
      '--go-output': 'goOutput',
      '--ts-output': 'tsOutput',
    }[argument]
    if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
    options[key] = resolve(productRoot, argv[index + 1])
    index += 1
  }
  return options
}

function assertContract(contract) {
  if (contract?.schemaVersion !== 1 || contract?.name !== 'code-languages') {
    throw new Error('code languages must use schemaVersion 1')
  }
  if (contract.plainText !== 'plain text') throw new Error('code languages must keep "plain text"')
  const values = new Set()
  for (const pair of contract.languages ?? []) {
    if (!Array.isArray(pair) || pair.length !== 2 || pair.some((part) => typeof part !== 'string' || !part)) {
      throw new Error('each language is a [value, label] pair')
    }
    if (pair[0] !== pair[0].toLowerCase()) throw new Error(`language value ${pair[0]} must be lowercase`)
    if (values.has(pair[0]) || pair[0] === contract.plainText) throw new Error(`language ${pair[0]} is listed twice`)
    values.add(pair[0])
  }
  if (values.size === 0) throw new Error('code languages must list languages')
  for (const [name, value] of Object.entries(contract.shortNames ?? {})) {
    if (!/^[a-z0-9_]+$/u.test(name) || values.has(name)) throw new Error(`short name ${name} must be one lowercase word, not a language's own`)
    if (!values.has(value)) throw new Error(`short name ${name} names no language`)
  }
  for (const name of contract.unreadNames ?? []) {
    if (!values.has(name)) throw new Error(`unread name ${name} is no language`)
  }
  for (const [language, prism] of Object.entries(contract.prismNames ?? {})) {
    if (!values.has(language) || !/^[a-z0-9-]+$/u.test(prism)) throw new Error(`Prism name ${prism} of ${language} is invalid`)
  }
  for (const name of contract.unmarkedNames ?? []) {
    if (!values.has(name)) throw new Error(`unmarked name ${name} is no language`)
  }
}

function renderGo(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-code-languages.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    'package app',
    '',
    `const plainTextCodeLanguage = ${JSON.stringify(contract.plainText)}`,
    '',
    'var codeLanguageValues = map[string]struct{}{',
    ...contract.languages.map(([value]) => `\t${JSON.stringify(value)}: {},`),
    '}',
    '',
    'var codeLanguageShortNames = map[string]string{',
    ...Object.entries(contract.shortNames).map(([name, value]) => `\t${JSON.stringify(name)}: ${JSON.stringify(value)},`),
    '}',
    '',
    'var unreadCodeLanguageNames = map[string]struct{}{',
    ...contract.unreadNames.map((name) => `\t${JSON.stringify(name)}: {},`),
    '}',
    '',
    'var codeLanguagePrismNames = map[string]string{',
    ...Object.entries(contract.prismNames).map(([language, prism]) => `\t${JSON.stringify(language)}: ${JSON.stringify(prism)},`),
    '}',
    '',
    'var unmarkedCodeLanguageNames = map[string]struct{}{',
    ...contract.unmarkedNames.map((name) => `\t${JSON.stringify(name)}: {},`),
    '}',
    '',
  ]
  const formatted = spawnSync('gofmt', [], { input: lines.join('\n'), encoding: 'utf8' })
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
  return formatted.stdout
}

function renderTypeScript(contract, digest) {
  return [
    '// Code generated by scripts/generate-code-languages.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    `export const PLAIN_TEXT_CODE_LANGUAGE = ${JSON.stringify(contract.plainText)};`,
    '',
    'export const CODE_LANGUAGE_LABELS: ReadonlyArray<readonly [string, string]> = [',
    ...contract.languages.map((pair) => `  ${JSON.stringify(pair)},`),
    '];',
    '',
    'export const CODE_LANGUAGE_SHORT_NAMES: Readonly<Record<string, string>> = {',
    ...Object.entries(contract.shortNames).map(([name, value]) => `  ${JSON.stringify(name)}: ${JSON.stringify(value)},`),
    '};',
    '',
    `export const UNREAD_CODE_LANGUAGE_NAMES: ReadonlySet<string> = new Set(${JSON.stringify(contract.unreadNames)});`,
    '',
    'export const CODE_LANGUAGE_PRISM_NAMES: Readonly<Record<string, string>> = {',
    ...Object.entries(contract.prismNames).map(([language, prism]) => `  ${JSON.stringify(language)}: ${JSON.stringify(prism)},`),
    '};',
    '',
  ].join('\n')
}

function checkOrWrite(path, expected, check) {
  if (check) {
    let actual = ''
    try {
      actual = readFileSync(path, 'utf8')
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
    if (actual !== expected) {
      process.stderr.write(`stale generated output: ${relative(productRoot, path)}\n`)
      process.exitCode = 1
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, expected)
}

function main() {
  const options = parseArgs(process.argv.slice(2))
  const source = readFileSync(options.contract, 'utf8')
  const contract = JSON.parse(source)
  assertContract(contract)
  const digest = createHash('sha256').update(source).digest('hex')
  checkOrWrite(options.goOutput, renderGo(contract, digest), options.check)
  checkOrWrite(options.tsOutput, renderTypeScript(contract, digest), options.check)
}

try {
  main()
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
}
