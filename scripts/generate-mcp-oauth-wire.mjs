import { createHash } from 'node:crypto'
import { spawnSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { wireOptionalTag } from './wire-field-tag.mjs'

const scriptsRoot = dirname(fileURLToPath(import.meta.url))
const productRoot = resolve(scriptsRoot, '..')

function parseArgs(argv) {
  const options = {
    check: false,
    contract: resolve(productRoot, 'contracts/mcp-oauth-wire.json'),
    goOutput: resolve(productRoot, 'internal/app/mcp_oauth_wire.generated.go'),
    tsOutput: resolve(productRoot, 'web/src/mcpOAuthWire.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') {
      options.check = true
      continue
    }
    const key = { '--contract': 'contract', '--go-output': 'goOutput', '--ts-output': 'tsOutput' }[argument]
    if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
    options[key] = resolve(productRoot, argv[index + 1])
    index += 1
  }
  return options
}

function assertContract(contract) {
  if (contract?.schemaVersion !== 1 || contract?.name !== 'mcp-oauth') {
    throw new Error('MCP OAuth contract must use schemaVersion 1')
  }
  for (const key of ['typescriptImports', 'operations', 'bounds', 'constants', 'errors', 'records']) {
    if (!Array.isArray(contract[key]) || contract[key].length === 0) throw new Error(`contract requires ${key}`)
  }
  const unique = (values, label) => {
    if (new Set(values).size !== values.length) throw new Error(`${label} contains duplicates`)
  }
  for (const key of ['operations', 'bounds', 'constants', 'errors', 'records']) {
    unique(contract[key].map((item) => item.goName), `Go ${key}`)
    unique(contract[key].map((item) => item.tsName), `TypeScript ${key}`)
  }
  unique(contract.typescriptImports.map((item) => item.name), 'TypeScript imports')
  for (const item of contract.typescriptImports) {
    if (!item.name || !item.from?.startsWith('./')) throw new Error(`invalid TypeScript import: ${item.name}`)
  }
  for (const operation of contract.operations) {
    const validPath = operation.path === '/mcp/connections'
      || operation.path === '/mcp/connections/{id}'
      || operation.path === '/mcp/connection-codes'
      || operation.path === '/mcp/connection-codes/exchange'
      || operation.path.startsWith('/mcp/oauth/requests/{request}')
    if (!['DELETE', 'GET', 'POST'].includes(operation.method) || !validPath) {
      throw new Error(`invalid MCP OAuth operation: ${operation.tsName}`)
    }
  }
  for (const bound of contract.bounds) {
    if (!Number.isSafeInteger(bound.value) || bound.value <= 0) throw new Error(`invalid MCP OAuth bound: ${bound.tsName}`)
  }
  for (const record of contract.records) {
    if (!Array.isArray(record.fields) || record.fields.length === 0) throw new Error(`record requires fields: ${record.tsName}`)
    unique(record.fields.map((field) => field.goName), `${record.goName} Go fields`)
    unique(record.fields.map((field) => field.jsonName), `${record.goName} JSON fields`)
    for (const field of record.fields) {
      if (!field.goName || !field.jsonName || !field.goType || !field.tsType) {
        throw new Error(`incomplete field: ${record.tsName}.${field.jsonName}`)
      }
      if (Boolean(field.nullable) !== field.goType.startsWith('*')) {
        throw new Error(`nullable fields must use matching Go pointers: ${record.tsName}.${field.jsonName}`)
      }
    }
  }
}

function renderGo(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-mcp-oauth-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    'package app',
    '',
    'const (',
  ]
  for (const operation of contract.operations) {
    lines.push(`\t${operation.goName}Method = ${JSON.stringify(operation.method)}`)
    lines.push(`\t${operation.goName}Path = ${JSON.stringify(operation.path)}`)
  }
  lines.push('')
  for (const bound of contract.bounds) lines.push(`\t${bound.goName} = ${bound.value}`)
  lines.push('')
  for (const constant of contract.constants) lines.push(`\t${constant.goName} = ${JSON.stringify(constant.value)}`)
  lines.push('')
  for (const error of contract.errors) lines.push(`\t${error.goName} = ${JSON.stringify(error.value)}`)
  lines.push(')', '')
  for (const record of contract.records) {
    lines.push(`type ${record.goName} struct {`)
    for (const field of record.fields) {
      lines.push(`\t${field.goName} ${field.goType} \`json:"${field.jsonName}${wireOptionalTag(field)}"\``)
    }
    lines.push('}', '')
  }
  const formatted = spawnSync('gofmt', [], { input: `${lines.join('\n')}\n`, encoding: 'utf8' })
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
  return formatted.stdout
}

function renderTypeScript(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-mcp-oauth-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
  ]
  for (const item of contract.typescriptImports) {
    lines.push(`import type { ${item.name} } from ${JSON.stringify(item.from)};`)
  }
  lines.push('', 'export const mcpOAuthOperations = {')
  for (const operation of contract.operations) {
    lines.push(`  ${operation.tsName}: { method: ${JSON.stringify(operation.method)}, path: ${JSON.stringify(operation.path)} },`)
  }
  lines.push('} as const;', '', 'export const mcpOAuthBounds = {')
  for (const bound of contract.bounds) lines.push(`  ${bound.tsName}: ${bound.value},`)
  lines.push('} as const;', '', 'export const mcpOAuthConstants = {')
  for (const constant of contract.constants) lines.push(`  ${constant.tsName}: ${JSON.stringify(constant.value)},`)
  lines.push('} as const;', '', 'export const mcpOAuthErrorCodes = {')
  for (const error of contract.errors) lines.push(`  ${error.tsName}: ${JSON.stringify(error.value)},`)
  lines.push('} as const;', '')
  for (const record of contract.records) {
    lines.push(`export type ${record.tsName} = {`)
    for (const field of record.fields) {
      lines.push(`  ${field.jsonName}${field.optional ? '?' : ''}: ${field.tsType}${field.nullable ? ' | null' : ''};`)
    }
    lines.push('};', '')
  }
  while (lines.at(-1) === '') lines.pop()
  return `${lines.join('\n')}\n`
}

function checkOrWrite(path, expected, check) {
  if (check) {
    let actual = ''
    try { actual = readFileSync(path, 'utf8') } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
    if (actual !== expected) {
      process.stderr.write(`stale generated output: ${relative(productRoot, path)}\n`)
      process.exitCode = 1
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, expected)
}

try {
  const options = parseArgs(process.argv.slice(2))
  const contractSource = readFileSync(options.contract, 'utf8')
  const contract = JSON.parse(contractSource)
  assertContract(contract)
  const digest = createHash('sha256').update(contractSource).digest('hex')
  checkOrWrite(options.goOutput, renderGo(contract, digest), options.check)
  checkOrWrite(options.tsOutput, renderTypeScript(contract, digest), options.check)
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
}
