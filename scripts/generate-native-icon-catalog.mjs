import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

// The built-in icon catalog holds the official internal names, picker tooltip
// aliases and colors. It carries no glyph assets; Leafen draws its own glyphs.

const scriptsRoot = dirname(fileURLToPath(import.meta.url))
const productRoot = resolve(scriptsRoot, '..')

function parseArgs(argv) {
  const options = {
    check: false,
    contract: resolve(productRoot, 'contracts/native-icon-catalog.json'),
    goOutput: resolve(productRoot, 'internal/app/native_icon_catalog.generated.go'),
    tsOutput: resolve(productRoot, 'web/src/nativeIconCatalog.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') {
      options.check = true
      continue
    }
    const key = {
      '--contract': 'contract',
      '--go-output': 'goOutput',
      '--ts-output': 'tsOutput',
    }[argument]
    if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
    options[key] = resolve(productRoot, argv[index + 1])
    index += 1
  }
  return options
}

const namePattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/u
const aliasPattern = /^[a-z0-9.]+(?:-[a-z0-9.]+)*$/u

function assertContract(contract) {
  if (contract?.schemaVersion !== 1 || contract?.name !== 'native-icon-catalog' || !contract.version) {
    throw new Error('native icon catalog contract must use schemaVersion 1 and a version')
  }
  const colors = contract.colors
  if (!Array.isArray(colors) || colors.length === 0 || new Set(colors).size !== colors.length ||
    !colors.includes(contract.defaultColor)) {
    throw new Error('native icon catalog colors must be unique and include the default color')
  }
  if (!Array.isArray(contract.icons) || contract.icons.length === 0) {
    throw new Error('native icon catalog requires icons')
  }
  const names = contract.icons.map(({ name }) => name)
  if (new Set(names).size !== names.length) throw new Error('native icon names contain duplicates')
  if (names.some((name, index) => index > 0 && names[index - 1] >= name)) {
    throw new Error('native icon names must stay in picker order')
  }
  const aliases = new Set()
  for (const icon of contract.icons) {
    if (!namePattern.test(icon.name) || Object.keys(icon).some((key) => key !== 'name' && key !== 'alias')) {
      throw new Error(`native icon ${icon.name} is invalid`)
    }
    if (icon.alias === undefined) continue
    if (!aliasPattern.test(icon.alias) || icon.alias === icon.name || aliases.has(icon.alias)) {
      throw new Error(`native icon alias ${icon.alias} is invalid`)
    }
    aliases.add(icon.alias)
  }
}

function renderGo(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-native-icon-catalog.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    'package app',
    '',
    `const nativeIconCatalogVersion = ${JSON.stringify(contract.version)}`,
    '',
    `const nativeIconDefaultColor = ${JSON.stringify(contract.defaultColor)}`,
    '',
    `var nativeIconColorOrder = []string{${contract.colors.map((color) => JSON.stringify(color)).join(', ')}}`,
    '',
    '// nativeIconCatalog maps each internal name to its picker tooltip alias,',
    '// which is empty when the tooltip is the name itself.',
    'var nativeIconCatalog = map[string]string{',
  ]
  for (const icon of contract.icons) {
    lines.push(`\t${JSON.stringify(icon.name)}: ${JSON.stringify(icon.alias ?? '')},`)
  }
  lines.push('}')
  const formatted = spawnSync('gofmt', [], { input: `${lines.join('\n')}\n`, encoding: 'utf8' })
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
  return formatted.stdout
}

function renderTypeScript(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-native-icon-catalog.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    `export const NATIVE_ICON_CATALOG_VERSION = ${JSON.stringify(contract.version)};`,
    `export const NATIVE_ICON_DEFAULT_COLOR = ${JSON.stringify(contract.defaultColor)};`,
    `export const NATIVE_ICON_COLORS = [${contract.colors.map((color) => JSON.stringify(color)).join(', ')}] as const;`,
    'export type NativeIconColor = (typeof NATIVE_ICON_COLORS)[number];',
    '',
    '/** Internal name and picker tooltip alias (omitted when it is the name), in picker order. */',
    'export const NATIVE_ICONS: ReadonlyArray<readonly [name: string, alias?: string]> = [',
  ]
  for (const icon of contract.icons) {
    lines.push(icon.alias === undefined
      ? `  [${JSON.stringify(icon.name)}],`
      : `  [${JSON.stringify(icon.name)}, ${JSON.stringify(icon.alias)}],`)
  }
  lines.push('];')
  return `${lines.join('\n')}\n`
}

function checkOrWrite(path, expected, check) {
  if (check) {
    let actual = ''
    try {
      actual = readFileSync(path, 'utf8')
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
    if (actual !== expected) {
      process.stderr.write(`stale generated output: ${relative(productRoot, path)}\n`)
      process.exitCode = 1
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, expected)
}

try {
  const options = parseArgs(process.argv.slice(2))
  const contractSource = readFileSync(options.contract, 'utf8')
  const contract = JSON.parse(contractSource)
  assertContract(contract)
  const digest = createHash('sha256').update(contractSource).digest('hex')
  checkOrWrite(options.goOutput, renderGo(contract, digest), options.check)
  checkOrWrite(options.tsOutput, renderTypeScript(contract, digest), options.check)
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
}
