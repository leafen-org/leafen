import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { wireOptionalTag } from './wire-field-tag.mjs'

const productRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')

function options(argv) {
  const result = {
    check: false,
    contract: resolve(productRoot, 'contracts/comment-wire.json'),
    goOutput: resolve(productRoot, 'internal/app/comment_wire.generated.go'),
    tsOutput: resolve(productRoot, 'web/src/commentWire.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') result.check = true
    else {
      const key = { '--contract': 'contract', '--go-output': 'goOutput', '--ts-output': 'tsOutput' }[argument]
      if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
      result[key] = resolve(productRoot, argv[++index])
    }
  }
  return result
}

function validate(contract) {
  if (contract?.schemaVersion !== 1 || contract?.name !== 'comment') throw new Error('comment contract must use schemaVersion 1')
  if (!Array.isArray(contract.operations) || contract.operations.length !== 31) throw new Error('comment contract requires thirty-one operations')
  if (!Array.isArray(contract.records) || contract.records.length === 0) throw new Error('comment contract requires records')
  for (const value of Object.values(contract.bounds ?? {})) {
    if (!Number.isSafeInteger(value) || value < 1) throw new Error('comment bounds must be positive integers')
  }
  const unique = (values, label) => {
    if (new Set(values).size !== values.length) throw new Error(`${label} contains duplicates`)
  }
  unique(contract.operations.map(({ goName }) => goName), 'Go operations')
  unique(contract.operations.map(({ tsName }) => tsName), 'TypeScript operations')
  unique(contract.records.map(({ goName }) => goName), 'Go records')
  for (const record of contract.records) unique(record.fields.map(({ jsonName }) => jsonName), `${record.goName} fields`)
}

function renderGo(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-comment-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    'package app',
    '',
    'import "encoding/json"',
    '',
    'const (',
  ]
  for (const operation of contract.operations) {
    lines.push(`\t${operation.goName}Method = ${JSON.stringify(operation.method)}`)
    lines.push(`\t${operation.goName}Path = ${JSON.stringify(operation.path)}`)
  }
  lines.push('')
  const boundNames = {
    listPage: 'commentListPageSize', deleteTurn: 'commentDeleteTurnSize',
    identifierRunes: 'commentIdentifierRunes', bodyBytes: 'commentBodyBytes',
    cursorBytes: 'commentCursorBytes',
    notificationInboxScan: 'commentNotificationInboxScanSize',
    notificationInboxDefault: 'commentNotificationInboxDefaultSize',
    notificationInboxMax: 'commentNotificationInboxMaxSize',
    notificationInboxPageSet: 'commentNotificationInboxPageSetSize',
    notificationSyncActivities: 'notificationSyncActivitiesSize',
    notificationReadSelected: 'notificationReadSelectedSize',
    notificationReadTurn: 'notificationReadTurnSize',
    notificationArchiveSelected: 'notificationArchiveSelectedSize',
    reactionEmojiBytes: 'commentReactionEmojiBytes',
  }
  for (const [name, value] of Object.entries(contract.bounds)) lines.push(`\t${boundNames[name]} = ${value}`)
  lines.push('')
  for (const [name, value] of Object.entries(contract.errors)) {
    const goName = `errorCodeComment${name[0].toUpperCase()}${name.slice(1)}`
    lines.push(`\t${goName} = ${JSON.stringify(value)}`)
  }
  lines.push('\tcommentDeletionStatusPending = "pending"')
  lines.push('\tcommentDeletionStatusComplete = "complete"')
  lines.push(')', '')
  for (const record of contract.records) {
    lines.push(`type ${record.goName} struct {`)
    for (const field of record.fields) {
      const suffix = wireOptionalTag(field)
      lines.push(`\t${field.goName} ${field.goType} \`json:"${field.jsonName}${suffix}"\``)
    }
    lines.push('}', '')
  }
  const formatted = spawnSync('gofmt', [], { input: `${lines.join('\n')}\n`, encoding: 'utf8' })
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
  return formatted.stdout
}

function renderTypeScript(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-comment-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    'export const commentOperations = {',
  ]
  for (const operation of contract.operations) lines.push(`  ${operation.tsName}: { method: ${JSON.stringify(operation.method)}, path: ${JSON.stringify(operation.path)} },`)
  lines.push('} as const;', '', `export const commentBounds = ${JSON.stringify(contract.bounds, null, 2)} as const;`)
  lines.push('', `export const commentErrorCodes = ${JSON.stringify(contract.errors, null, 2)} as const;`, '')
  for (const record of contract.records) {
    lines.push(`export type ${record.tsName} = {`)
    for (const field of record.fields) lines.push(`  ${field.jsonName}${field.optional ? '?' : ''}: ${field.tsType};`)
    lines.push('};', '')
  }
  return `${lines.join('\n').trimEnd()}\n`
}

function emit(path, expected, check) {
  if (check) {
    let actual = ''
    try { actual = readFileSync(path, 'utf8') } catch (error) { if (error?.code !== 'ENOENT') throw error }
    if (actual !== expected) {
      process.stderr.write(`stale generated output: ${relative(productRoot, path)}\n`)
      process.exitCode = 1
    }
  } else {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, expected)
  }
}

try {
  const resolved = options(process.argv.slice(2))
  const source = readFileSync(resolved.contract, 'utf8')
  const contract = JSON.parse(source)
  validate(contract)
  const digest = createHash('sha256').update(source).digest('hex')
  emit(resolved.goOutput, renderGo(contract, digest), resolved.check)
  emit(resolved.tsOutput, renderTypeScript(contract, digest), resolved.check)
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
}
