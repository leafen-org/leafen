import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const scriptsRoot = dirname(fileURLToPath(import.meta.url))
const productRoot = resolve(scriptsRoot, '..')

function options(argv) {
  const result = {
    check: false,
    contract: resolve(productRoot, 'contracts/database-automation-wire.json'),
    goOutput: resolve(productRoot, 'internal/app/database_automation_wire.generated.go'),
    tsOutput: resolve(productRoot, 'web/src/databaseAutomationWire.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') result.check = true
    else {
      const key = { '--contract': 'contract', '--go-output': 'goOutput', '--ts-output': 'tsOutput' }[argument]
      if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
      result[key] = resolve(productRoot, argv[++index])
    }
  }
  return result
}

function assertContract(contract) {
  if (contract?.schemaVersion !== 3 || contract?.name !== 'database-automation') {
    throw new Error('database automation contract must use schemaVersion 3')
  }
  for (const key of [
    'listPage', 'evaluationChunk', 'identifierRunes', 'nameRunes', 'documentBytes', 'resultBytes',
    'dailyIntervalDays', 'weeklyIntervalWeeks', 'monthlyIntervalMonths', 'yearlyIntervalYears', 'scheduleAdmissionChunk', 'scheduleMaxRuns', 'deliveryClaimChunk', 'deliveryLeaseMilliseconds',
    'deliveryMaxAttempts', 'deliveryRetryBaseMilliseconds', 'deliveryRetryMaxMilliseconds',
    'deliveryPayloadBytes', 'deliveryResponseBytes',
  ]) {
    if (!Number.isSafeInteger(contract.bounds?.[key]) || contract.bounds[key] < 1) throw new Error(`invalid bound: ${key}`)
  }
  for (const key of [
    'scopeTypes', 'triggerTypes', 'triggerConditionTypes', 'triggerConditionOperators', 'triggerModes', 'scheduleFrequencies',
    'statuses', 'outcomeStatuses', 'pausedReasons', 'deliveryChannels', 'deliveryStatuses', 'operations',
  ]) {
    if (!Array.isArray(contract[key]) || contract[key].length < 1) throw new Error(`invalid list: ${key}`)
  }
  for (const value of Object.values(contract.errors ?? {})) {
    if (!/^LEAFEN_[A-Z_]+$/u.test(value)) throw new Error(`invalid error: ${value}`)
  }
}

const title = (value) => value.split(/[_-]/u).map((part) => part[0].toUpperCase() + part.slice(1)).join('')

