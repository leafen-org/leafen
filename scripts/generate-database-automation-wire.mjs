function write(path, expected, check) {
  if (check) {
    let actual = ''
    try { actual = readFileSync(path, 'utf8') } catch (error) { if (error?.code !== 'ENOENT') throw error }
    if (actual !== expected) {
      process.stderr.write(`stale generated output: ${relative(productRoot, path)}\n`)
      process.exitCode = 1
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, expected)
}

const config = options(process.argv.slice(2))
const contractSource = readFileSync(config.contract, 'utf8')
const contract = JSON.parse(contractSource)
assertContract(contract)
const digest = createHash('sha256').update(contractSource).digest('hex')
write(config.goOutput, renderGo(contract, digest), config.check)
write(config.tsOutput, renderTypeScript(contract, digest), config.check)
