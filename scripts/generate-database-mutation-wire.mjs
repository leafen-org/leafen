import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const productRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')

function options(argv) {
  const result = {
    check: false,
    contract: resolve(productRoot, 'contracts/database-mutation-wire.json'),
    goOutput: resolve(productRoot, 'internal/app/database_mutation_wire.generated.go'),
    tsOutput: resolve(productRoot, 'web/src/databaseMutationWire.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') {
      result.check = true
      continue
    }
    const key = { '--contract': 'contract', '--go-output': 'goOutput', '--ts-output': 'tsOutput' }[argument]
    if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
    result[key] = resolve(productRoot, argv[index + 1])
    index += 1
  }
  return result
}

function validate(contract) {
  if (contract?.schemaVersion !== 1 || contract?.name !== 'database-mutation') {
    throw new Error('database mutation contract must use schemaVersion 1')
  }
  for (const key of ['operations', 'targetKinds', 'statuses', 'phases', 'records']) {
    if (!Array.isArray(contract[key]) || contract[key].length === 0) throw new Error(`contract requires ${key}`)
  }
  for (const key of ['requestIdRunes', 'itemsPerTurn', 'jobsPerBurst']) {
    if (!Number.isSafeInteger(contract.bounds?.[key]) || contract.bounds[key] < 1) throw new Error(`invalid bound: ${key}`)
  }
  for (const [key, value] of Object.entries(contract.errors ?? {})) {
    if (!key || !/^LEAFEN_[A-Z_]+$/u.test(value)) throw new Error(`invalid error: ${key}`)
  }
  const unique = (values, label) => {
    if (new Set(values).size !== values.length) throw new Error(`${label} contains duplicates`)
  }
  unique(contract.operations.map(({ name }) => name), 'operations')
  unique(contract.targetKinds, 'target kinds')
  unique(contract.statuses, 'statuses')
  unique(contract.phases, 'phases')
}

const goIdentifier = (prefix, value) => prefix + (value === 'requestIdReused'
  ? 'RequestIDReused'
  : value[0].toUpperCase() + value.slice(1))

function renderGo(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-database-mutation-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`, '', 'package app', '', 'const (',
  ]
  for (const operation of contract.operations) {
    lines.push(`\t${operation.goName}Method = ${JSON.stringify(operation.method)}`)
    lines.push(`\t${operation.goName}Path = ${JSON.stringify(operation.path)}`)
  }
  lines.push('', `\tmaxDatabaseMutationRequestIDRunes = ${contract.bounds.requestIdRunes}`)
  lines.push(`\tdatabaseMutationItemsPerTurn = ${contract.bounds.itemsPerTurn}`)
  lines.push(`\tdatabaseMutationJobsPerBurst = ${contract.bounds.jobsPerBurst}`, '')
  for (const [name, value] of Object.entries(contract.errors)) {
    lines.push(`\t${goIdentifier('errorCodeDatabaseMutation', name)} = ${JSON.stringify(value)}`)
  }
  lines.push('')
  for (const value of contract.targetKinds) lines.push(`\t${goIdentifier('databaseMutationTarget', value)} = ${JSON.stringify(value)}`)
  lines.push('')
  for (const value of contract.statuses) lines.push(`\t${goIdentifier('databaseMutationStatus', value)} = ${JSON.stringify(value)}`)
  lines.push('')
  for (const value of contract.phases) lines.push(`\t${goIdentifier('databaseMutationPhase', value)} = ${JSON.stringify(value)}`)
  lines.push(')', '')
  for (const record of contract.records) {
    lines.push(`type ${record.goName} struct {`)
    for (const field of record.fields) lines.push(`\t${field.goName} ${field.goType} \`json:"${field.jsonName}"\``)
    lines.push('}', '')
  }
  const formatted = spawnSync('gofmt', [], { input: `${lines.join('\n')}\n`, encoding: 'utf8' })
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
  return formatted.stdout
}

function renderTypeScript(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-database-mutation-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    'import type { GraphMutationReceipt } from "./contentGraph";', '',
    'export const databaseMutationOperations = {',
  ]
  for (const operation of contract.operations) {
    lines.push(`  ${operation.tsName}: { method: ${JSON.stringify(operation.method)}, path: ${JSON.stringify(operation.path)} },`)
  }
  lines.push('} as const;', '', 'export const databaseMutationBounds = {')
  for (const [name, value] of Object.entries(contract.bounds)) lines.push(`  ${name}: ${value},`)
  lines.push('} as const;', '', 'export const databaseMutationErrorCodes = {')
  for (const [name, value] of Object.entries(contract.errors)) lines.push(`  ${name}: ${JSON.stringify(value)},`)
  lines.push('} as const;', '')
  const enumType = (valuesName, typeName, values) => {
    lines.push(`export const ${valuesName} = {`)
    for (const value of values) lines.push(`  ${value}: ${JSON.stringify(value)},`)
    lines.push('} as const;')
    lines.push(`export type ${typeName} = typeof ${valuesName}[keyof typeof ${valuesName}];`, '')
  }
  enumType('databaseMutationTargetKinds', 'DatabaseMutationTargetKind', contract.targetKinds)
  enumType('databaseMutationStatuses', 'DatabaseMutationStatus', contract.statuses)
  enumType('databaseMutationPhases', 'DatabaseMutationPhase', contract.phases)
  for (const record of contract.records) {
    lines.push(`export type ${record.tsName} = {`)
    for (const field of record.fields) lines.push(`  ${field.jsonName}: ${field.tsType};`)
    lines.push('};', '')
  }
  while (lines.at(-1) === '') lines.pop()
  return `${lines.join('\n')}\n`
}

function publish(path, expected, check) {
  if (check) {
    let actual = ''
    try { actual = readFileSync(path, 'utf8') } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
    if (actual !== expected) {
      process.stderr.write(`stale generated output: ${relative(productRoot, path)}\n`)
      process.exitCode = 1
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, expected)
}

try {
  const configured = options(process.argv.slice(2))
  const contractSource = readFileSync(configured.contract, 'utf8')
  const contract = JSON.parse(contractSource)
  validate(contract)
  const digest = createHash('sha256').update(contractSource).digest('hex')
  publish(configured.goOutput, renderGo(contract, digest), configured.check)
  publish(configured.tsOutput, renderTypeScript(contract, digest), configured.check)
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
}
