import { spawnSync } from 'node:child_process'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

// Writes the short names Intl gives time zones in each language formulas
// write dates in, as Notion shows a date's own zone ("EDT" in English,
// "GMT-4" in Korean), for the server (English) and the web to share. A name
// is kept by zone and offset in minutes, and only where it is not the plain
// offset both write otherwise: "GMT+9", "GMT-3:30", and "UTC" at no offset.
// Zones are the names the system's time zone data holds, aliases among them,
// read in mid-January and mid-July of a fixed year, so the tables change only
// with Node's and the system's time zone data.

const productRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const goOutput = resolve(productRoot, 'internal/app/time_zone_names.generated.go')
const tsOutput = resolve(productRoot, 'web/src/lib/timeZoneNames.generated.ts')
const zoneRoot = '/usr/share/zoneinfo'
const check = process.argv.includes('--check')
const languages = [['en', 'en-US'], ['ko', 'ko-KR']]

function zoneNames() {
  return readdirSync(zoneRoot, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile() || entry.isSymbolicLink())
    .map((entry) => `${entry.parentPath.slice(zoneRoot.length + 1)}/${entry.name}`.replace(/^\//, ''))
    .filter((name) => /^[A-Z][A-Za-z0-9_+-]*(\/[A-Za-z0-9_+-]+)*$/.test(name) && !/^(posix|right)\//.test(name) && name !== 'Factory')
    .filter((name) => {
      try {
        new Intl.DateTimeFormat('en-US', { timeZone: name })
        return true
      } catch {
        return false
      }
    })
    .sort()
}

function part(locale, zone, when, style) {
  return new Intl.DateTimeFormat(locale, { timeZone: zone, timeZoneName: style })
    .formatToParts(when).find(({ type }) => type === 'timeZoneName')?.value ?? ''
}

function offsetMinutes(zone, when) {
  const match = /^GMT(?:([+-])(\d{2}):(\d{2}))?$/.exec(part('en-US', zone, when, 'longOffset'))
  if (!match) throw new Error(`unreadable offset for ${zone}`)
  return match[1] ? (match[1] === '-' ? -1 : 1) * (Number(match[2]) * 60 + Number(match[3])) : 0
}

function plainLabel(offset) {
  if (offset === 0) return 'UTC'
  const minutes = Math.abs(offset) % 60
  return `GMT${offset < 0 ? '-' : '+'}${Math.floor(Math.abs(offset) / 60)}${minutes ? `:${String(minutes).padStart(2, '0')}` : ''}`
}

const seasons = [new Date(Date.UTC(2026, 0, 15, 12)), new Date(Date.UTC(2026, 6, 15, 12))]
const zones = zoneNames()
const tables = Object.fromEntries(languages.map(([language, locale]) => {
  const table = []
  for (const zone of zones) {
    const names = new Map()
    for (const when of seasons) {
      const offset = offsetMinutes(zone, when)
      const name = part(locale, zone, when, 'short')
      if (name !== plainLabel(offset)) names.set(offset, name)
    }
    if (names.size) table.push([zone, [...names].sort(([left], [right]) => left - right)])
  }
  return [language, table]
}))

function goTable(table) {
  return `map[string]map[int]string{
${table.map(([zone, names]) => `\t${JSON.stringify(zone)}: {${names.map(([offset, name]) => `${offset}: ${JSON.stringify(name)}`).join(', ')}},`).join('\n')}
}`
}

const header = `// Code generated by scripts/generate-time-zone-names.mjs. DO NOT EDIT.
// ICU ${process.versions.icu}, time zone data ${process.versions.tz}.
`
const goSource = `${header}
package app

// englishTimeZoneShortNames are the English short names of time zones, by
// zone and offset in minutes, where they are not the plain offset.
var englishTimeZoneShortNames = ${goTable(tables.en)}

// koreanTimeZoneShortNames are the Korean ones (database_formula_locale.go).
var koreanTimeZoneShortNames = ${goTable(tables.ko)}
`
const formatted = spawnSync('gofmt', [], { input: goSource, encoding: 'utf8' })
if (formatted.status !== 0) throw new Error(`gofmt: ${formatted.stderr}`)
const go = formatted.stdout
const ts = `${header}
// The short names of time zones in each language formulas write dates in, by
// zone and offset in minutes, where they are not the plain offset.
export const TIME_ZONE_SHORT_NAMES: Readonly<Record<string, Readonly<Record<string, Readonly<Record<number, string>>>>>> = {
${languages.map(([language]) => `  ${language}: {
${tables[language].map(([zone, names]) => `    ${JSON.stringify(zone)}: { ${names.map(([offset, name]) => `${JSON.stringify(String(offset))}: ${JSON.stringify(name)}`).join(', ')} },`).join('\n')}
  },`).join('\n')}
};
`

for (const [path, content] of [[goOutput, go], [tsOutput, ts]]) {
  if (check) {
    const current = readFileSync(path, 'utf8')
    if (current.split('\n').slice(2).join('\n') !== content.split('\n').slice(2).join('\n')) {
      throw new Error(`${path} is stale; run node scripts/generate-time-zone-names.mjs`)
    }
  } else {
    writeFileSync(path, content)
  }
}
