import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

// The working-day calendars the formulas count deadlines on
// (internal/app/business_calendars.json, which the server embeds) as the
// web's formulas read them, so both evaluators skip the same days.
//
// Usage: node scripts/generate-business-calendar.mjs [--check]

const productRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = resolve(productRoot, 'internal/app/business_calendars.json')
const outputPath = resolve(productRoot, 'web/src/shared/businessCalendar.generated.ts')

const calendars = JSON.parse(readFileSync(sourcePath, 'utf8'))
const shaped = Object.fromEntries(Object.entries(calendars).sort(([left], [right]) => left.localeCompare(right)).map(([code, calendar]) => [code, {
  weekend: calendar.weekend,
  years: Object.keys(calendar.years).sort(),
  holidays: Object.fromEntries(Object.values(calendar.years).flat().sort(([left], [right]) => left.localeCompare(right))),
}]))
const output = [
  '// Code generated by scripts/generate-business-calendar.mjs from internal/app/business_calendars.json. DO NOT EDIT.',
  '',
  'export type BusinessCalendar = {',
  '  /** The days of the week (0 for Sunday) no one works. */',
  '  weekend: readonly number[];',
  '  /** The years whose holidays the calendar holds. */',
  '  years: readonly string[];',
  '  /** Each holiday\'s name by its date (YYYY-MM-DD). */',
  '  holidays: Readonly<Record<string, string>>;',
  '};',
  '',
  `export const BUSINESS_CALENDARS: Readonly<Record<string, BusinessCalendar>> = ${JSON.stringify(shaped, null, 2)};`,
  '',
].join('\n')

if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(outputPath, 'utf8') } catch {}
  if (current !== output) {
    console.error('web/src/shared/businessCalendar.generated.ts is out of date: run node scripts/generate-business-calendar.mjs')
    process.exit(1)
  }
} else {
  writeFileSync(outputPath, output)
}
