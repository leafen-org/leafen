import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { wireOptionalTag } from './wire-field-tag.mjs'

const scriptsRoot = dirname(fileURLToPath(import.meta.url))
const productRoot = resolve(scriptsRoot, '..')

function parseArgs(argv) {
  const options = {
    check: false,
    contract: resolve(productRoot, 'contracts/form-wire.json'),
    goOutput: resolve(productRoot, 'internal/app/form_wire.generated.go'),
    tsOutput: resolve(productRoot, 'web/src/formWire.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') {
      options.check = true
      continue
    }
    const key = { '--contract': 'contract', '--go-output': 'goOutput', '--ts-output': 'tsOutput' }[argument]
    if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
    options[key] = resolve(productRoot, argv[index + 1])
    index += 1
  }
  return options
}

function assertUnique(values, label) {
  if (new Set(values).size !== values.length) throw new Error(`${label} contains duplicates`)
}

function assertContract(contract) {
  if (contract?.schemaVersion !== 1 || contract?.name !== 'form') throw new Error('form contract must use schemaVersion 1')
  for (const key of ['operations', 'bounds', 'errors', 'enums', 'records']) {
    if (!Array.isArray(contract[key]) || contract[key].length === 0) throw new Error(`contract requires ${key}`)
  }
  assertUnique(contract.operations.map((entry) => entry.name), 'operations')
  assertUnique(contract.bounds.map((entry) => entry.goName), 'Go bounds')
  assertUnique(contract.errors.map((entry) => entry.goName), 'Go errors')
  assertUnique(contract.records.map((entry) => entry.goName), 'Go records')
  assertUnique(contract.records.map((entry) => entry.tsName), 'TypeScript records')
  for (const record of contract.records) assertUnique(record.fields.map((field) => field.jsonName), `${record.tsName} fields`)
}

function renderGo(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-form-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    'package app',
    '',
    'const (',
  ]
  for (const operation of contract.operations) {
    lines.push(`\t${operation.goName} = ${JSON.stringify(operation.method)}`)
  }
  lines.push(`\tformPath = ${JSON.stringify(contract.operations[0].path)}`, '')
  for (const bound of contract.bounds) lines.push(`\t${bound.goName} = ${bound.value}`)
  lines.push('')
  for (const error of contract.errors) lines.push(`\t${error.goName} = ${JSON.stringify(error.value)}`)
  for (const enumeration of contract.enums) {
    lines.push('')
    for (const value of enumeration.values) lines.push(`\t${value.goName} = ${JSON.stringify(value.value)}`)
  }
  lines.push(')', '')
  for (const record of contract.records) {
    lines.push(`type ${record.goName} struct {`)
    for (const field of record.fields) {
      const suffix = wireOptionalTag(field)
      lines.push(`\t${field.goName} ${field.goType} \`json:"${field.jsonName}${suffix}"\``)
    }
    lines.push('}', '')
  }
  const formatted = spawnSync('gofmt', [], { input: `${lines.join('\n')}\n`, encoding: 'utf8' })
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
  return formatted.stdout
}

function renderTypeScript(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-form-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    'export const formOperations = {',
  ]
  for (const operation of contract.operations) {
    lines.push(`  ${operation.tsName}: { method: ${JSON.stringify(operation.method)}, path: ${JSON.stringify(operation.path)} },`)
  }
  lines.push('} as const;', '', 'export const formBounds = {')
  for (const bound of contract.bounds) lines.push(`  ${bound.tsName}: ${bound.value},`)
  lines.push('} as const;', '', 'export const formErrorCodes = {')
  for (const error of contract.errors) lines.push(`  ${error.tsName}: ${JSON.stringify(error.value)},`)
  lines.push('} as const;', '')
  for (const enumeration of contract.enums) {
    lines.push(`export const ${enumeration.tsValuesName} = {`)
    for (const value of enumeration.values) lines.push(`  ${value.tsName}: ${JSON.stringify(value.value)},`)
    lines.push('} as const;', `export type ${enumeration.tsName} = typeof ${enumeration.tsValuesName}[keyof typeof ${enumeration.tsValuesName}];`, '')
  }
  for (const record of contract.records) {
    lines.push(`export interface ${record.tsName} {`)
    for (const field of record.fields) lines.push(`  ${field.jsonName}${field.optional ? '?' : ''}: ${field.tsType};`)
    lines.push('}', '')
  }
  const requestTypes = contract.records
    .map((record) => record.tsName)
    .filter((name) => name.endsWith('Request'))
  lines.push(`export type FormTransportRequest = ${requestTypes.join(' | ')};`)
  return `${lines.join('\n')}\n`
}

function writeOrCheck(path, expected, check) {
  if (check) {
    const actual = readFileSync(path, 'utf8')
    if (actual !== expected) throw new Error(`${relative(productRoot, path)} is stale`)
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, expected)
}

const options = parseArgs(process.argv.slice(2))
const bytes = readFileSync(options.contract)
const contract = JSON.parse(bytes)
assertContract(contract)
const digest = createHash('sha256').update(bytes).digest('hex')
writeOrCheck(options.goOutput, renderGo(contract, digest), options.check)
writeOrCheck(options.tsOutput, renderTypeScript(contract, digest), options.check)
