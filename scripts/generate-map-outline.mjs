// Builds the offline map outline the map view draws when external tiles
// are off or fail: Natural Earth 1:110m land, land borders and populated
// places (public domain, https://www.naturalearthdata.com/).
//
//   node scripts/generate-map-outline.mjs \
//     --land ne_110m_land.geojson \
//     --borders ne_110m_admin_0_boundary_lines_land.geojson \
//     --places ne_110m_populated_places_simple.geojson \
//     --version 5.1.2
//   node scripts/generate-map-outline.mjs --empty
//
// Coordinates are rounded to 0.01° (about 1 km), which the 1:110m scale
// never needs more than.

import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const productRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const output = resolve(productRoot, 'web/src/components/database/mapOutline.generated.ts')

function parseArgs(argv) {
  const options = { empty: false }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--empty') {
      options.empty = true
      continue
    }
    const key = { '--land': 'land', '--borders': 'borders', '--places': 'places', '--version': 'version' }[argument]
    if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
    options[key] = argv[index + 1]
    index += 1
  }
  if (!options.empty && !(options.land && options.borders && options.places && options.version)) {
    throw new Error('pass --land, --borders, --places and --version, or --empty')
  }
  return options
}

const round = (value) => Math.round(value * 100) / 100

function flatRing(points) {
  const flat = []
  for (const [lon, lat] of points) {
    const x = round(lon)
    const y = round(lat)
    if (flat.length >= 2 && flat[flat.length - 2] === x && flat[flat.length - 1] === y) continue
    flat.push(x, y)
  }
  return flat
}

function read(path) {
  const text = readFileSync(path, 'utf8')
  return { collection: JSON.parse(text), sha256: createHash('sha256').update(text).digest('hex') }
}

function rings(collection, kinds) {
  const result = []
  for (const feature of collection.features ?? []) {
    const geometry = feature.geometry
    if (!geometry || !kinds.includes(geometry.type)) continue
    const parts = geometry.type === 'Polygon' || geometry.type === 'MultiLineString'
      ? geometry.coordinates
      : geometry.type === 'MultiPolygon' ? geometry.coordinates.flat() : [geometry.coordinates]
    for (const part of parts) {
      const flat = flatRing(part)
      if (flat.length >= 4) result.push(flat)
    }
  }
  return result
}

function places(collection) {
  return (collection.features ?? []).flatMap((feature) => {
    const properties = feature.properties ?? {}
    const [lon, lat] = feature.geometry?.coordinates ?? []
    const name = String(properties.name ?? properties.NAME ?? '').trim()
    const rank = Number(properties.scalerank ?? properties.SCALERANK)
    if (!name || !Number.isFinite(lon) || !Number.isFinite(lat) || !Number.isFinite(rank)) return []
    return [{ name, lon: round(lon), lat: round(lat), rank }]
  }).sort((left, right) => left.rank - right.rank || left.name.localeCompare(right.name))
}

const options = parseArgs(process.argv.slice(2))
let source = ''
let outline = { land: [], borders: [], places: [] }
if (!options.empty) {
  const land = read(options.land)
  const borders = read(options.borders)
  const populated = read(options.places)
  source = `Natural Earth ${options.version} 1:110m (land ${land.sha256.slice(0, 12)}, ` +
    `borders ${borders.sha256.slice(0, 12)}, places ${populated.sha256.slice(0, 12)})`
  outline = {
    land: rings(land.collection, ['Polygon', 'MultiPolygon']),
    borders: rings(borders.collection, ['LineString', 'MultiLineString']),
    places: places(populated.collection),
  }
}
writeFileSync(output, [
  '// Code generated by scripts/generate-map-outline.mjs. DO NOT EDIT.',
  '// Natural Earth data is in the public domain: https://www.naturalearthdata.com/about/terms-of-use/',
  '',
  'export type MapOutlinePlace = { name: string; lon: number; lat: number; rank: number };',
  '',
  '/** Rings and lines are flat [lon, lat, lon, lat, ...] lists in degrees. */',
  'export const mapOutline: {',
  '  source: string;',
  '  land: readonly (readonly number[])[];',
  '  borders: readonly (readonly number[])[];',
  '  places: readonly MapOutlinePlace[];',
  '} = {',
  `  source: ${JSON.stringify(source)},`,
  `  land: ${JSON.stringify(outline.land)},`,
  `  borders: ${JSON.stringify(outline.borders)},`,
  `  places: ${JSON.stringify(outline.places)},`,
  '};',
  '',
].join('\n'))
process.stdout.write(`map outline: ${outline.land.length} land rings, ${outline.borders.length} borders, ${outline.places.length} places\n`)
