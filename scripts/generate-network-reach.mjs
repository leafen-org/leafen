// Who opens an address by its host alone — this computer, its network, or
// anyone — is one table (contracts/network-reach.json), which the server
// (internal/app/network_reach.go) and the web (web/src/lib/addressReach.ts,
// beside its copy) both read from the files this writes; --check says whether
// they are current.
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const scriptsRoot = dirname(fileURLToPath(import.meta.url))
const productRoot = resolve(scriptsRoot, '..')

function parseArgs(argv) {
  const options = {
    check: false,
    contract: resolve(productRoot, 'contracts/network-reach.json'),
    goOutput: resolve(productRoot, 'internal/app/network_reach.generated.go'),
    tsOutput: resolve(productRoot, 'web/src/lib/networkReach.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') {
      options.check = true
      continue
    }
    const key = { '--contract': 'contract', '--go-output': 'goOutput', '--ts-output': 'tsOutput' }[argument]
    if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
    options[key] = resolve(productRoot, argv[index + 1])
    index += 1
  }
  return options
}

function assertSortedList(values, label, pattern) {
  if (!Array.isArray(values) || values.length === 0 || values.some((value) => typeof value !== 'string' || !pattern.test(value))) {
    throw new Error(`${label} must be a nonempty list of ${pattern}`)
  }
  if (new Set(values).size !== values.length) throw new Error(`${label} contains duplicates`)
  if ([...values].sort().join('\n') !== values.join('\n')) throw new Error(`${label} must be sorted`)
}

const NAME = /^[a-z0-9-]+$/u
const SUFFIX = /^(\.[a-z0-9-]+)+$/u
const ADDRESS = /^(\d{1,3}(\.\d{1,3}){3}|[0-9a-f:]*:[0-9a-f:]*)$/u
const RANGE = /^(\d{1,3}(\.\d{1,3}){3}\/\d{1,2}|[0-9a-f:]*:[0-9a-f:]*\/\d{1,3})$/u

function assertContract(contract) {
  if (contract?.schemaVersion !== 1 || contract?.name !== 'network-reach') throw new Error('network reach must use schemaVersion 1')
  const { thisComputer, network } = contract
  assertSortedList(thisComputer?.names, 'thisComputer.names', NAME)
  assertSortedList(thisComputer?.suffixes, 'thisComputer.suffixes', SUFFIX)
  assertSortedList(thisComputer?.ranges, 'thisComputer.ranges', RANGE)
  assertSortedList(thisComputer?.unspecified, 'thisComputer.unspecified', ADDRESS)
  if (typeof network?.oneLabelNames !== 'boolean') throw new Error('network.oneLabelNames must be a boolean')
  assertSortedList(network?.suffixes, 'network.suffixes', SUFFIX)
  assertSortedList(network?.ranges, 'network.ranges', RANGE)
  // The network's link-local ranges, whose addresses each computer gives
  // itself on one link: the network's, but none a person opens from
  // elsewhere in it, so none is named as one to open.
  assertSortedList(network?.selfAssignedRanges, 'network.selfAssignedRanges', RANGE)
  if (network.selfAssignedRanges.some((value) => !network.ranges.includes(value))) {
    throw new Error('network.selfAssignedRanges must be among network.ranges')
  }
}

function header(digest) {
  return ['// Code generated by scripts/generate-network-reach.mjs. DO NOT EDIT.', `// Contract SHA-256: ${digest}`, '']
}

function renderGo(contract, digest) {
  const { thisComputer, network } = contract
  const strings = (values) => `[]string{${values.map((value) => JSON.stringify(value)).join(', ')}}`
  const prefixes = (values) => `[]netip.Prefix{${values.map((value) => `netip.MustParsePrefix(${JSON.stringify(value)})`).join(', ')}}`
  const addresses = (values) => `[]netip.Addr{${values.map((value) => `netip.MustParseAddr(${JSON.stringify(value)})`).join(', ')}}`
  const lines = [
    ...header(digest),
    'package app',
    '',
    'import "net/netip"',
    '',
    `const networkOneLabelNames = ${network.oneLabelNames}`,
    '',
    'var (',
    `\tthisComputerHostNames = ${strings(thisComputer.names)}`,
    `\tthisComputerHostSuffixes = ${strings(thisComputer.suffixes)}`,
    `\tthisComputerRanges = ${prefixes(thisComputer.ranges)}`,
    `\tunspecifiedAddresses = ${addresses(thisComputer.unspecified)}`,
    `\tnetworkHostSuffixes = ${strings(network.suffixes)}`,
    `\tnetworkRanges = ${prefixes(network.ranges)}`,
    `\tnetworkSelfAssignedRanges = ${prefixes(network.selfAssignedRanges)}`,
    ')',
    '',
  ]
  const formatted = spawnSync('gofmt', [], { input: lines.join('\n'), encoding: 'utf8' })
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
  return formatted.stdout
}

function renderTypeScript(contract, digest) {
  const { thisComputer, network } = contract
  return [
    ...header(digest),
    '/** Who opens an address by its host alone: this computer, its network, or anyone (contracts/network-reach.json). */',
    'export const networkReach = {',
    '  thisComputer: {',
    `    names: ${JSON.stringify(thisComputer.names)},`,
    `    suffixes: ${JSON.stringify(thisComputer.suffixes)},`,
    `    ranges: ${JSON.stringify(thisComputer.ranges)},`,
    `    unspecified: ${JSON.stringify(thisComputer.unspecified)},`,
    '  },',
    '  network: {',
    `    oneLabelNames: ${network.oneLabelNames},`,
    `    suffixes: ${JSON.stringify(network.suffixes)},`,
    `    ranges: ${JSON.stringify(network.ranges)},`,
    `    selfAssignedRanges: ${JSON.stringify(network.selfAssignedRanges)},`,
    '  },',
    '} as const;',
    '',
  ].join('\n')
}

function checkOrWrite(path, expected, check) {
  if (check) {
    let actual = ''
    try {
      actual = readFileSync(path, 'utf8')
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
    if (actual !== expected) {
      process.stderr.write(`stale generated output: ${relative(productRoot, path)}\n`)
      process.exitCode = 1
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, expected)
}

function main() {
  const options = parseArgs(process.argv.slice(2))
  const source = readFileSync(options.contract, 'utf8')
  const contract = JSON.parse(source)
  assertContract(contract)
  const digest = createHash('sha256').update(source).digest('hex')
  checkOrWrite(options.goOutput, renderGo(contract, digest), options.check)
  checkOrWrite(options.tsOutput, renderTypeScript(contract, digest), options.check)
}

try {
  main()
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
}
