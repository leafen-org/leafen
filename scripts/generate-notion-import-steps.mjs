// Writes what a person does to let Leafen read their Notion — the import
// screen's own words, in each language the catalog has them all — for the
// server, whose MCP answer without a Notion connection gives an agent the
// same steps to walk with the person one at a time, the last putting the
// token in this server's import screen (notion_import_handoff.go). With them
// go the move's first words, which the import screen's move text has an
// agent say and a move's first sources answer leads with
// (notion_migration_first_words.go): a language without its own has the
// English ones, which the agent says in the person's language.
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const productRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const locales = resolve(productRoot, 'web/src/locales')
const output = resolve(productRoot, 'internal/app/notion_import_steps.generated.go')
const check = process.argv.includes('--check')

const read = (language, namespace) => {
  const file = resolve(locales, language, `${namespace}.json`)
  return existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : {}
}

function personText(language) {
  const dialog = read(language, 'importDialog')
  const steps = dialog.notionSteps
  const handoff = read(language, 'common').generated?.notionImportHandoff
  // A language without every part has none: the server gives English.
  if (!steps || typeof steps.title !== 'string' || !Array.isArray(steps.items) || steps.items.length === 0
    || !handoff || typeof handoff.link !== 'string' || typeof handoff.rest !== 'string'
    || typeof dialog.tokenLabel !== 'string' || typeof dialog.handoff?.saveToken !== 'string') return null
  const link = handoff.link.replace(/\{\{(field|save)\}\}/gu, (_, key) => key === 'field' ? dialog.tokenLabel : dialog.handoff.saveToken)
  const firstWords = typeof dialog.handoff.firstWords === 'string' ? dialog.handoff.firstWords : read('en', 'importDialog').handoff.firstWords
  return { steps: steps.items, token: link, pasteInstead: handoff.rest, firstWords }
}

const entries = readdirSync(locales, { withFileTypes: true })
  .filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort()
  .map((language) => [language, personText(language)]).filter(([, text]) => text)
const generated = `// Code generated by scripts/generate-notion-import-steps.mjs. DO NOT EDIT.

package app

var notionImportPersonTexts = map[string]notionImportPersonText{
${entries.map(([language, text]) => `\t${JSON.stringify(language)}: {\n\t\tSteps: []string{\n${text.steps.map((step) => `\t\t\t${JSON.stringify(step)},`).join('\n')}\n\t\t},\n\t\tToken:        ${JSON.stringify(text.token)},\n\t\tPasteInstead: ${JSON.stringify(text.pasteInstead)},\n\t\tFirstWords:   ${JSON.stringify(text.firstWords)},\n\t},`).join('\n')}
}
`
if (check) {
  if (!existsSync(output) || readFileSync(output, 'utf8') !== generated) {
    console.error('stale generated output: internal/app/notion_import_steps.generated.go (run node scripts/generate-notion-import-steps.mjs)')
    process.exit(1)
  }
} else {
  writeFileSync(output, generated)
}
