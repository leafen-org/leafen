import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { wireOptionalTag } from './wire-field-tag.mjs'

const scriptsRoot = dirname(fileURLToPath(import.meta.url))
const productRoot = resolve(scriptsRoot, '..')

function parseArgs(argv) {
  const options = {
    check: false,
    contract: resolve(productRoot, 'contracts/collaboration-storage-wire.json'),
    goOutput: resolve(productRoot, 'internal/app/collaboration_storage_wire.generated.go'),
    tsOutput: resolve(productRoot, 'web/src/collaborationStorageWire.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') {
      options.check = true
      continue
    }
    const key = { '--contract': 'contract', '--go-output': 'goOutput', '--ts-output': 'tsOutput' }[argument]
    if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
    options[key] = resolve(productRoot, argv[index + 1])
    index += 1
  }
  return options
}

function assertContract(contract) {
  if (contract?.schemaVersion !== 1 || contract?.name !== 'collaboration-storage') {
    throw new Error('collaboration storage contract must use schemaVersion 1')
  }
  if (!contract.operation?.method || !contract.operation?.path || !Array.isArray(contract.statuses) ||
      contract.statuses.length !== 3 || !contract.response?.goName || !contract.response?.tsName) {
    throw new Error('collaboration storage contract is incomplete')
  }
  const unique = (values, label) => {
    if (new Set(values).size !== values.length) throw new Error(`${label} contains duplicates`)
  }
  unique(contract.statuses.map(({ value }) => value), 'status values')
  unique(contract.statuses.map(({ goName }) => goName), 'Go status names')
  unique(contract.response.fields.map(({ jsonName }) => jsonName), 'response fields')
}

function renderGo(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-collaboration-storage-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`, '', 'package app', '', 'const (',
    `\tcollaborationStorageStatusMethod = ${JSON.stringify(contract.operation.method)}`,
    `\tcollaborationStorageStatusPath = apiRoot + ${JSON.stringify(contract.operation.path)}`,
  ]
  for (const status of contract.statuses) lines.push(`\t${status.goName} = ${JSON.stringify(status.value)}`)
  lines.push(')', '', `type ${contract.response.goName} struct {`)
  for (const field of contract.response.fields) {
    lines.push(`\t${field.goName} ${field.goType} \`json:"${field.jsonName}${wireOptionalTag(field)}"\``)
  }
  lines.push('}', '')
  const formatted = spawnSync('gofmt', [], { input: `${lines.join('\n')}\n`, encoding: 'utf8' })
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
  return formatted.stdout
}

function renderTypeScript(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-collaboration-storage-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`, '', 'export const collaborationStorageOperation = {',
    `  method: ${JSON.stringify(contract.operation.method)},`,
    `  path: ${JSON.stringify(contract.operation.path)},`,
    '} as const;', '', 'export const collaborationStorageStatuses = {',
  ]
  for (const status of contract.statuses) lines.push(`  ${status.tsName}: ${JSON.stringify(status.value)},`)
  lines.push(
    '} as const;',
    'export type CollaborationStorageStatus = typeof collaborationStorageStatuses[keyof typeof collaborationStorageStatuses];',
    '', `export type ${contract.response.tsName} = {`,
  )
  for (const field of contract.response.fields) {
    lines.push(`  ${field.jsonName}${field.optional ? '?' : ''}: ${field.tsType};`)
  }
  lines.push('};')
  return `${lines.join('\n')}\n`
}

function checkOrWrite(path, expected, check) {
  if (check) {
    let actual = ''
    try { actual = readFileSync(path, 'utf8') } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
    if (actual !== expected) {
      process.stderr.write(`stale generated output: ${relative(productRoot, path)}\n`)
      process.exitCode = 1
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, expected)
}

try {
  const options = parseArgs(process.argv.slice(2))
  const contractSource = readFileSync(options.contract, 'utf8')
  const contract = JSON.parse(contractSource)
  assertContract(contract)
  const digest = createHash('sha256').update(contractSource).digest('hex')
  checkOrWrite(options.goOutput, renderGo(contract, digest), options.check)
  checkOrWrite(options.tsOutput, renderTypeScript(contract, digest), options.check)
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
}
