import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { wireOptionalTag } from './wire-field-tag.mjs'

const scriptsRoot = dirname(fileURLToPath(import.meta.url))
const productRoot = resolve(scriptsRoot, '..')

function parseArgs(argv) {
  const options = {
    check: false,
    contract: resolve(productRoot, 'contracts/page-analytics-wire.json'),
    goOutput: resolve(productRoot, 'internal/app/page_analytics_wire.generated.go'),
    tsOutput: resolve(productRoot, 'web/src/pageAnalyticsWire.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') {
      options.check = true
      continue
    }
    const key = {
      '--contract': 'contract',
      '--go-output': 'goOutput',
      '--ts-output': 'tsOutput',
    }[argument]
    if (!key || !argv[index + 1]) {
      throw new Error(`unknown or incomplete argument: ${argument}`)
    }
    options[key] = resolve(productRoot, argv[index + 1])
    index += 1
  }
  return options
}

function assertUnique(values, label) {
  if (new Set(values).size !== values.length) throw new Error(`${label} contains duplicates`)
}

function assertContract(contract) {
  if (contract?.schemaVersion !== 1 || contract?.name !== 'page-analytics') {
    throw new Error('page analytics contract must use schemaVersion 1')
  }
  for (const key of ['bounds', 'errors', 'enums', 'records', 'unions']) {
    if (!Array.isArray(contract[key]) || contract[key].length === 0) {
      throw new Error(`contract requires ${key}`)
    }
  }
  assertUnique(contract.records.map((record) => record.goName), 'Go records')
  assertUnique(contract.records.map((record) => record.tsName), 'TypeScript records')
  const recordNames = new Set(contract.records.map((record) => record.tsName))
  for (const record of contract.records) {
    assertUnique(record.fields.map((field) => field.jsonName), `${record.tsName} fields`)
  }
  assertUnique(contract.unions.map((union) => union.tsName), 'TypeScript unions')
  for (const union of contract.unions) {
    if (union.members.length === 0 || union.members.some((member) => !recordNames.has(member))) {
      throw new Error(`${union.tsName} references an unknown or empty member set`)
    }
    assertUnique(union.members, `${union.tsName} members`)
  }
}

function renderGo(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-page-analytics-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    'package app',
    '',
    'const (',
  ]
  for (const bound of contract.bounds) lines.push(`\t${bound.goName} = ${bound.value}`)
  lines.push('')
  for (const error of contract.errors) {
    lines.push(`\t${error.goName} = ${JSON.stringify(error.value)}`)
  }
  for (const enumeration of contract.enums) {
    lines.push('')
    for (const value of enumeration.values) {
      lines.push(`\t${value.goName} = ${JSON.stringify(value.value)}`)
    }
  }
  lines.push(')', '')
  for (const record of contract.records) {
    lines.push(`type ${record.goName} struct {`)
    for (const field of record.fields) {
      const suffix = wireOptionalTag(field)
      lines.push(`\t${field.goName} ${field.goType} \`json:"${field.jsonName}${suffix}"\``)
    }
    lines.push('}', '')
  }
  const formatted = spawnSync('gofmt', [], {
    input: `${lines.join('\n')}\n`,
    encoding: 'utf8',
  })
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
  return formatted.stdout
}

function renderTypeScript(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-page-analytics-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    'export const pageAnalyticsBounds = {',
  ]
  for (const bound of contract.bounds) lines.push(`  ${bound.tsName}: ${bound.value},`)
  lines.push('} as const;', '', 'export const pageAnalyticsErrorCodes = {')
  for (const error of contract.errors) {
    lines.push(`  ${error.tsName}: ${JSON.stringify(error.value)},`)
  }
  lines.push('} as const;', '')
  for (const enumeration of contract.enums) {
    lines.push(`export const ${enumeration.tsValuesName} = {`)
    for (const value of enumeration.values) {
      lines.push(`  ${value.tsName}: ${JSON.stringify(value.value)},`)
    }
    lines.push('} as const;')
    lines.push(
      `export type ${enumeration.tsName} = typeof ${enumeration.tsValuesName}[keyof typeof ${enumeration.tsValuesName}];`,
      '',
    )
  }
  for (const record of contract.records) {
    lines.push(`export type ${record.tsName} = {`)
    for (const field of record.fields) {
      lines.push(`  ${field.jsonName}${field.optional ? '?' : ''}: ${field.tsType};`)
    }
    lines.push('};', '')
  }
  for (const union of contract.unions) {
    lines.push(`export type ${union.tsName} =`)
    for (const member of union.members) lines.push(`  | ${member}`)
    lines.push('', '')
  }
  while (lines.at(-1) === '') lines.pop()
  return `${lines.join('\n')}\n`
}

function checkOrWrite(path, expected, check) {
  if (check) {
    let actual = ''
    try {
      actual = readFileSync(path, 'utf8')
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
    if (actual !== expected) {
      process.stderr.write(`stale generated output: ${relative(productRoot, path)}\n`)
      process.exitCode = 1
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, expected)
}

try {
  const options = parseArgs(process.argv.slice(2))
  const contractSource = readFileSync(options.contract, 'utf8')
  const contract = JSON.parse(contractSource)
  assertContract(contract)
  const digest = createHash('sha256').update(contractSource).digest('hex')
  checkOrWrite(options.goOutput, renderGo(contract, digest), options.check)
  checkOrWrite(options.tsOutput, renderTypeScript(contract, digest), options.check)
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
}
