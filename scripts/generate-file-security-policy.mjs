import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const scriptsRoot = dirname(fileURLToPath(import.meta.url))
const productRoot = resolve(scriptsRoot, '..')

function parseArgs(argv) {
  const options = {
    check: false,
    contract: resolve(productRoot, 'contracts/file-security-policy.json'),
    goOutput: resolve(productRoot, 'internal/app/file_security_policy.generated.go'),
    tsOutput: resolve(productRoot, 'web/src/fileSecurityPolicy.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') {
      options.check = true
      continue
    }
    const key = {
      '--contract': 'contract',
      '--go-output': 'goOutput',
      '--ts-output': 'tsOutput',
    }[argument]
    if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
    options[key] = resolve(productRoot, argv[index + 1])
    index += 1
  }
  return options
}

function assertStringList(values, label) {
  if (!Array.isArray(values) || values.length === 0 || values.some((value) => typeof value !== 'string' || !value)) {
    throw new Error(`${label} must be a nonempty string list`)
  }
  if (new Set(values).size !== values.length) throw new Error(`${label} contains duplicates`)
  if ([...values].sort().join('\n') !== values.join('\n')) throw new Error(`${label} must be sorted`)
}

function assertContract(contract) {
  if (contract?.schemaVersion !== 1 || contract?.name !== 'file-security-policy') {
    throw new Error('file security policy must use schemaVersion 1')
  }
  if (contract.defaultContentType !== 'application/octet-stream') {
    throw new Error('file security policy must retain the binary fallback')
  }
  if (!Number.isSafeInteger(contract.maxContentTypeLength) || contract.maxContentTypeLength < 1) {
    throw new Error('file security policy requires a positive MIME length bound')
  }
  for (const key of ['invalidContentType', 'unsafeType']) {
    if (!/^LEAFEN_[A-Z0-9_]+$/u.test(contract.errors?.[key] ?? '')) {
      throw new Error(`file security policy requires ${key}`)
    }
  }
  assertStringList(contract.activeContentTypes, 'activeContentTypes')
  assertStringList(contract.activeExtensions, 'activeExtensions')
  // HTML a build with the app platform keeps, to open only in a frame with no
  // origin (docs/app-platform.md 14): never served inline from Leafen's origin.
  if (contract.sandboxedHtml?.contentType !== 'text/html') throw new Error('sandboxedHtml must name text/html')
  assertStringList(contract.sandboxedHtml.extensions, 'sandboxedHtml.extensions')
  for (const extension of contract.sandboxedHtml.extensions) {
    if (!contract.activeExtensions.includes(extension)) throw new Error(`sandboxedHtml extension ${extension} must stay an active extension`)
  }
}

function renderGo(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-file-security-policy.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    'package app',
    '',
    'const (',
    `\tdefaultFileContentType = ${JSON.stringify(contract.defaultContentType)}`,
    `\tmaxFileContentTypeLength = ${contract.maxContentTypeLength}`,
    `\terrorCodeFileContentTypeInvalid = ${JSON.stringify(contract.errors.invalidContentType)}`,
    `\terrorCodeFileUnsafeType = ${JSON.stringify(contract.errors.unsafeType)}`,
    ')',
    '',
    'var activeFileContentTypes = map[string]struct{}{',
    ...contract.activeContentTypes.map((value) => `\t${JSON.stringify(value)}: {},`),
    '}',
    '',
    'var activeFileExtensions = map[string]struct{}{',
    ...contract.activeExtensions.map((value) => `\t${JSON.stringify(value)}: {},`),
    '}',
    '',
    `const sandboxedHTMLContentType = ${JSON.stringify(contract.sandboxedHtml.contentType)}`,
    '',
    'var sandboxedHTMLExtensions = map[string]struct{}{',
    ...contract.sandboxedHtml.extensions.map((value) => `\t${JSON.stringify(value)}: {},`),
    '}',
    '',
  ]
  const formatted = spawnSync('gofmt', [], { input: lines.join('\n'), encoding: 'utf8' })
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
  return formatted.stdout
}

function renderTypeScript(contract, digest) {
  return [
    '// Code generated by scripts/generate-file-security-policy.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    `export const defaultFileContentType = ${JSON.stringify(contract.defaultContentType)};`,
    `export const maxFileContentTypeLength = ${contract.maxContentTypeLength};`,
    'export const fileSecurityErrorCodes = {',
    `  invalidContentType: ${JSON.stringify(contract.errors.invalidContentType)},`,
    `  unsafeType: ${JSON.stringify(contract.errors.unsafeType)},`,
    '} as const;',
    '',
    `export const activeFileContentTypes = ${JSON.stringify(contract.activeContentTypes)} as const;`,
    `export const activeFileExtensions = ${JSON.stringify(contract.activeExtensions)} as const;`,
    `export const sandboxedHtmlContentType = ${JSON.stringify(contract.sandboxedHtml.contentType)};`,
    `export const sandboxedHtmlExtensions = ${JSON.stringify(contract.sandboxedHtml.extensions)} as const;`,
    '',
  ].join('\n')
}

function checkOrWrite(path, expected, check) {
  if (check) {
    let actual = ''
    try {
      actual = readFileSync(path, 'utf8')
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
    if (actual !== expected) {
      process.stderr.write(`stale generated output: ${relative(productRoot, path)}\n`)
      process.exitCode = 1
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, expected)
}

function main() {
  const options = parseArgs(process.argv.slice(2))
  const source = readFileSync(options.contract, 'utf8')
  const contract = JSON.parse(source)
  assertContract(contract)
  const digest = createHash('sha256').update(source).digest('hex')
  checkOrWrite(options.goOutput, renderGo(contract, digest), options.check)
  checkOrWrite(options.tsOutput, renderTypeScript(contract, digest), options.check)
}

try {
  main()
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
}
