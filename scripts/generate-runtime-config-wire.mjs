import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { wireOptionalTag } from './wire-field-tag.mjs'

const scriptsRoot = dirname(fileURLToPath(import.meta.url))
const productRoot = resolve(scriptsRoot, '..')

function parseArgs(argv) {
  const options = {
    check: false,
    contract: resolve(productRoot, 'contracts/runtime-config-wire.json'),
    goOutput: resolve(productRoot, 'internal/app/runtime_config_wire.generated.go'),
    tsOutput: resolve(productRoot, 'web/src/runtimeConfigWire.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') {
      options.check = true
      continue
    }
    const key = {
      '--contract': 'contract',
      '--go-output': 'goOutput',
      '--ts-output': 'tsOutput',
    }[argument]
    if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
    options[key] = resolve(productRoot, argv[index + 1])
    index += 1
  }
  return options
}

function assertContract(contract) {
  if (contract?.schemaVersion !== 2 || contract?.name !== 'runtime-config') {
    throw new Error('runtime config wire contract must use schemaVersion 2')
  }
  if (!Array.isArray(contract.records) || contract.records.length === 0) {
    throw new Error('runtime config wire contract requires records')
  }
  const unique = (values, label) => {
    if (new Set(values).size !== values.length) throw new Error(`${label} contains duplicates`)
  }
  unique(contract.records.map(({ goName }) => goName), 'Go record names')
  unique(contract.records.map(({ tsName }) => tsName), 'TypeScript record names')
  for (const record of contract.records) {
    if (!record.goName || !record.tsName || !Array.isArray(record.fields) || record.fields.length === 0) {
      throw new Error('runtime config wire record is incomplete')
    }
    unique(record.fields.map(({ goName }) => goName), `${record.goName} Go fields`)
    unique(record.fields.map(({ jsonName }) => jsonName), `${record.goName} JSON fields`)
    for (const field of record.fields) {
      if (!field.goName || !field.jsonName || !field.goType || !field.tsType || typeof field.optional !== 'boolean') {
        throw new Error(`${record.goName} field is incomplete`)
      }
    }
  }
}

function renderGo(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-runtime-config-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    'package app',
    '',
  ]
  for (const record of contract.records) {
    lines.push(`type ${record.goName} struct {`)
    for (const field of record.fields) {
      const suffix = wireOptionalTag(field)
      lines.push(`\t${field.goName} ${field.goType} \`json:"${field.jsonName}${suffix}"\``)
    }
    lines.push('}', '')
  }
  const formatted = spawnSync('gofmt', [], { input: `${lines.join('\n')}\n`, encoding: 'utf8' })
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
  return formatted.stdout
}

function renderTypeScript(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-runtime-config-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
  ]
  for (const record of contract.records) {
    lines.push(`export type ${record.tsName} = {`)
    for (const field of record.fields) {
      lines.push(`  ${field.jsonName}${field.optional ? '?' : ''}: ${field.tsType};`)
    }
    lines.push('};', '')
  }
  while (lines.at(-1) === '') lines.pop()
  return `${lines.join('\n')}\n`
}

function checkOrWrite(path, expected, check) {
  if (check) {
    let actual = ''
    try {
      actual = readFileSync(path, 'utf8')
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
    if (actual !== expected) {
      process.stderr.write(`stale generated output: ${relative(productRoot, path)}\n`)
      process.exitCode = 1
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, expected)
}

try {
  const options = parseArgs(process.argv.slice(2))
  const contractSource = readFileSync(options.contract, 'utf8')
  const contract = JSON.parse(contractSource)
  assertContract(contract)
  const digest = createHash('sha256').update(contractSource).digest('hex')
  checkOrWrite(options.goOutput, renderGo(contract, digest), options.check)
  checkOrWrite(options.tsOutput, renderTypeScript(contract, digest), options.check)
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
}
