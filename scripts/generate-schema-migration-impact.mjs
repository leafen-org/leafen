import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const nativeSchemaMigrationPolicyConsumers = Object.freeze([
  'instance-product-export',
])

export const nativeSchemaMigrationMechanicalConsumers = Object.freeze([
  'affected-bpr-command-union',
  'backend-catalog',
  'current-public-revision',
  'schema-history',
  'semantic-bpr-ownership',
])

const normalizedStrings = (values) => [...new Set(values)].sort()
let parsedSource
let parsedLedger

function splitCSV(value) {
  return normalizedStrings(String(value ?? '').split(',').map((item) => item.trim()).filter(Boolean))
}

export function parseNativeSchemaMigrationImpact(source) {
  if (source === parsedSource) return parsedLedger
  const entryPattern = /^\s*\{version:\s*(\d+),\s*name:\s*"([^"]+)",\s*checksum:\s*([A-Za-z][A-Za-z0-9]*),\s*(?:impact:\s*schemaMigrationImpact\("([^"]*)",\s*"([^"]*)"\),\s*)?(?:up:\s*([A-Za-z][A-Za-z0-9]*),\s*)?(?:content:\s*([A-Za-z][A-Za-z0-9]*),\s*)?validate:\s*([A-Za-z][A-Za-z0-9]*)\},\s*$/gmu
  const entries = [...source.matchAll(entryPattern)].map((match) => ({
    version: Number(match[1]),
    name: match[2],
    checksumIdentifier: match[3],
    responsibilityCodes: splitCSV(match[4]),
    policyConsumers: splitCSV(match[5]),
    up: match[6] ?? '',
    content: match[7] ?? '',
    validate: match[8],
  }))
  const declaredEntryCount = [...source.matchAll(/^\s*\{version:\s*\d+,\s*name:/gmu)].length
  parsedSource = source
  parsedLedger = { declaredEntryCount, entries }
  return parsedLedger
}

export function nativeSchemaMigrationImpactSummary(entries) {
  return {
    migrationCount: entries.length,
    currentVersion: entries.at(-1)?.version ?? 0,
    responsibilityCodes: normalizedStrings(entries.flatMap(({ responsibilityCodes }) => responsibilityCodes)),
    policyConsumers: normalizedStrings(entries.flatMap(({ policyConsumers }) => policyConsumers)),
    mechanicalConsumers: [...nativeSchemaMigrationMechanicalConsumers],
  }
}

export function readNativeSchemaMigrationImpactLedger(source) {
  const { declaredEntryCount, entries } = parseNativeSchemaMigrationImpact(source)
  if (entries.length !== declaredEntryCount) {
    throw new Error('native schema migration impact ledger is not fully parseable')
  }
  // The first is the schema baseline (internal/app/schema_baseline.go), and
  // each later one the next version.
  const first = entries[0]?.version ?? 0
  const invalid = entries.filter(({ version, responsibilityCodes, policyConsumers }, index) => (
    version !== first + index || responsibilityCodes.length === 0 || policyConsumers.length === 0
  ))
  if (invalid.length > 0) {
    throw new Error(`native schema migration impact ledger is incomplete: ${invalid.map(({ version }) => version).join(',')}`)
  }
  return entries
}

export function renderNativeSchemaMigrationImpactGo(entries) {
  const currentVersion = entries.at(-1)?.version ?? 0
  const expectedPolicyConsumers = JSON.stringify(nativeSchemaMigrationPolicyConsumers)
  const exportVersions = entries
    .filter(({ policyConsumers }) => policyConsumers.includes('instance-product-export'))
    .map(({ version }) => version)
  if (
    currentVersion === 0 ||
    entries.some(({ policyConsumers }) => JSON.stringify(policyConsumers) !== expectedPolicyConsumers) ||
    exportVersions.length !== entries.length ||
    exportVersions.some((version, index) => version !== entries[0].version + index)
  ) throw new Error('instance product export policy does not cover the ordered migration frontier')
  return `// Code generated by scripts/generate-schema-migration-impact.mjs; DO NOT EDIT.
package app

const instanceProductExportPolicySchemaVersion = ${currentVersion}
`
}

const modulePath = fileURLToPath(import.meta.url)
const productRoot = resolve(dirname(modulePath), '..')
const appRoot = join(productRoot, 'internal', 'app')
const targetPath = join(appRoot, 'schema_migration_impact.generated.go')

// The ledger is split by version range: schema_migration_definitions.go
// holds the schema baseline and each schema_migration_definitions_NNNN.go
// the migrations from version NNNN on. Read in that order, they list every
// migration in version order.
export function readNativeSchemaMigrationDefinitionsSource(root = appRoot) {
  const later = readdirSync(root).filter((name) => /^schema_migration_definitions_\d{4}\.go$/u.test(name)).sort()
  return ['schema_migration_definitions.go', ...later].map((name) => readFileSync(join(root, name), 'utf8')).join('\n')
}

export function generateNativeSchemaMigrationImpact({ write = false } = {}) {
  const entries = readNativeSchemaMigrationImpactLedger(readNativeSchemaMigrationDefinitionsSource())
  const expected = renderNativeSchemaMigrationImpactGo(entries)
  if (write) {
    writeFileSync(targetPath, expected)
    return { changed: true, currentVersion: entries.at(-1).version }
  }
  const actual = readFileSync(targetPath, 'utf8')
  if (actual !== expected) throw new Error('generated schema migration impact is stale')
  return { changed: false, currentVersion: entries.at(-1).version }
}

if (process.argv[1] && resolve(process.argv[1]) === modulePath) {
  const write = process.argv.includes('--write')
  if (!write && !process.argv.includes('--check')) {
    throw new Error('use --check or --write')
  }
  const result = generateNativeSchemaMigrationImpact({ write })
  process.stdout.write(`schema migration impact ${write ? 'generated' : 'current'} at version ${result.currentVersion}\n`)
}
