import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { wireOptionalTag } from './wire-field-tag.mjs'

const scriptsRoot = dirname(fileURLToPath(import.meta.url))
const v2Root = resolve(scriptsRoot, '..')

function parseArgs(argv) {
  const options = {
    check: false,
    contract: resolve(v2Root, 'contracts/content-graph-wire.json'),
    goOutput: resolve(v2Root, 'internal/app/content_graph_wire.generated.go'),
    tsOutput: resolve(v2Root, 'web/src/contentGraphWire.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') {
      options.check = true
      continue
    }
    const key = {
      '--contract': 'contract',
      '--go-output': 'goOutput',
      '--ts-output': 'tsOutput',
    }[argument]
    if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
    options[key] = resolve(v2Root, argv[index + 1])
    index += 1
  }
  return options
}

function assertContract(contract) {
  if (contract?.schemaVersion !== 22 || contract?.name !== 'content-graph') {
    throw new Error('content graph wire contract must use schemaVersion 22')
  }
  for (const key of ['bounds', 'errors', 'enums', 'records']) {
    if (!Array.isArray(contract[key]) || contract[key].length === 0) {
      throw new Error(`content graph wire contract requires ${key}`)
    }
  }
  if (!Array.isArray(contract.operation?.variants) || !Array.isArray(contract.readItem?.variants)) {
    throw new Error('content graph wire contract requires operation and read variants')
  }
  if (!Array.isArray(contract.valueAliases) || contract.valueAliases.length === 0) {
    throw new Error('content graph wire contract requires value aliases')
  }
  if (!Array.isArray(contract.classifications) || contract.classifications.length === 0) {
    throw new Error('content graph wire contract requires classifications')
  }
  const uniqueValues = (values, label) => {
    if (new Set(values).size !== values.length) throw new Error(`${label} contains duplicates`)
  }
  uniqueValues(contract.records.map((record) => record.goName), 'Go record names')
  uniqueValues(contract.records.map((record) => record.tsName), 'TypeScript record names')
  uniqueValues(contract.valueAliases.map((alias) => alias.goName), 'Go value alias names')
  uniqueValues(contract.valueAliases.map((alias) => alias.tsName), 'TypeScript value alias names')
  uniqueValues(contract.classifications.map((item) => item.goName), 'Go classification names')
  uniqueValues(contract.classifications.map((item) => item.tsName), 'TypeScript classification names')
  for (const record of contract.records) {
    uniqueValues(record.fields.filter((field) => !field.goOnly).map((field) => field.jsonName), `${record.tsName} JSON fields`)
  }
  for (const classification of contract.classifications) {
    const enumeration = contract.enums.find(({ tsName }) => tsName === classification.enum)
    if (!enumeration) throw new Error(`${classification.tsName} names an unknown enum`)
    uniqueValues(classification.values, `${classification.tsName} values`)
    const allowed = new Set(enumeration.values.map(({ value }) => value))
    for (const value of classification.values) {
      if (!allowed.has(value)) throw new Error(`${classification.tsName} contains unknown value ${value}`)
    }
  }
}

// A Go-only field is what the server reads of a record's JSON beyond its
// fields, such as a field left out of it; it is never on the wire.
function goTag(field) {
  if (field.goOnly) return '`json:"-"`'
  const tags = [`json:"${field.jsonName}${wireOptionalTag(field)}"`]
  if (field.dbTag) tags.push(`db:"${field.dbTag}"`)
  return `\`${tags.join(' ')}\``
}

function renderGo(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-content-graph-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    'package app',
    '',
    'import "encoding/json"',
    '',
    'const (',
  ]
  for (const bound of contract.bounds) lines.push(`\t${bound.goName} = ${bound.value}`)
  lines.push('')
  for (const error of contract.errors) lines.push(`\t${error.goName} = ${JSON.stringify(error.value)}`)
  for (const enumeration of contract.enums) {
    lines.push('')
    for (const value of enumeration.values) lines.push(`\t${value.goName} = ${JSON.stringify(value.value)}`)
  }
  lines.push(')', '')
  for (const enumeration of contract.enums) {
    lines.push(`var ${enumeration.goValuesName} = map[string]struct{}{`)
    for (const value of enumeration.values) lines.push(`\t${value.goName}: {},`)
    lines.push('}', '')
  }
  for (const classification of contract.classifications) {
    const enumeration = contract.enums.find(({ tsName }) => tsName === classification.enum)
    const values = new Map(enumeration.values.map((value) => [value.value, value.goName]))
    lines.push(`var ${classification.goName} = map[string]struct{}{`)
    for (const value of classification.values) lines.push(`\t${values.get(value)}: {},`)
    lines.push('}', '')
  }
  for (const alias of contract.valueAliases) {
    lines.push(`type ${alias.goName} = ${alias.goType}`, '')
  }
  for (const record of contract.records) {
    lines.push(`type ${record.goName} struct {`)
    for (const field of record.fields) {
      // An old name kept on the wire says so, and what it was.
      if (field.deprecated) lines.push(`\t// Deprecated: ${field.deprecated}`)
      lines.push(`\t${field.goName} ${field.goType} ${goTag(field)}`)
    }
    lines.push('}', '')
  }
  lines.push(`type ${contract.operation.goName} struct {`)
  lines.push('\tKind string `json:"kind"`')
  for (const variant of contract.operation.variants) {
    lines.push(`\t${variant.goField} ${variant.goType} \`json:"${variant.jsonField},omitempty"\``)
  }
  lines.push('}', '')
  lines.push(`type ${contract.readItem.goName} struct {`)
  lines.push('\tKind string `json:"kind"`')
  lines.push('\tValue map[string]any `json:"value"`')
  lines.push('}', '')

  const formatted = spawnSync('gofmt', [], { input: `${lines.join('\n')}\n`, encoding: 'utf8' })
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
  return formatted.stdout
}

function renderTypeScript(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-content-graph-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    'export const graphWireBounds = {',
  ]
  for (const bound of contract.bounds) lines.push(`  ${bound.tsName}: ${bound.value},`)
  lines.push('} as const;', '', 'export const graphWireErrorCodes = {')
  for (const error of contract.errors) lines.push(`  ${error.tsName}: ${JSON.stringify(error.value)},`)
  lines.push('} as const;', '', 'export type GraphErrorCode = typeof graphWireErrorCodes[keyof typeof graphWireErrorCodes];', '')
  for (const enumeration of contract.enums) {
    const values = enumeration.values.map((value) => JSON.stringify(value.value)).join(', ')
    lines.push(`export const ${enumeration.tsValuesName} = [${values}] as const;`)
    lines.push(`export type ${enumeration.tsName} = typeof ${enumeration.tsValuesName}[number];`, '')
  }
  for (const classification of contract.classifications) {
    const values = classification.values.map((value) => JSON.stringify(value)).join(', ')
    lines.push(`export const ${classification.tsName} = [${values}] as const;`, '')
  }
  for (const record of contract.records) {
    lines.push(`export type ${record.tsName} = {`)
    for (const field of record.fields) {
      if (field.goOnly) continue
      if (field.deprecated) lines.push(`  /** @deprecated ${field.deprecated} */`)
      lines.push(`  ${field.jsonName}${field.optional ? '?' : ''}: ${field.tsType};`)
    }
    lines.push('};', '')
  }
  for (const alias of contract.valueAliases) {
    lines.push(`export type ${alias.tsName} = ${alias.tsType};`, '')
  }
  lines.push(`export type ${contract.operation.tsName} =`)
  contract.operation.variants.forEach((variant, index) => {
    const prefix = index === 0 ? '  ' : '  | '
    lines.push(`${prefix}{ kind: ${JSON.stringify(variant.kind)}; ${variant.jsonField}: ${variant.tsType} }`)
  })
  lines[lines.length - 1] += ';'
  lines.push('', `export type ${contract.readItem.tsName} =`)
  contract.readItem.variants.forEach((variant, index) => {
    const prefix = index === 0 ? '  ' : '  | '
    lines.push(`${prefix}{ kind: ${JSON.stringify(variant.kind)}; value: ${variant.tsType} }`)
  })
  lines[lines.length - 1] += ';'
  return `${lines.join('\n')}\n`
}

function checkOrWrite(path, expected, check) {
  if (check) {
    let actual = ''
    try {
      actual = readFileSync(path, 'utf8')
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
    if (actual !== expected) {
      process.stderr.write(`stale generated output: ${relative(v2Root, path)}\n`)
      process.exitCode = 1
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, expected)
}

function main() {
  const options = parseArgs(process.argv.slice(2))
  const source = readFileSync(options.contract, 'utf8')
  const contract = JSON.parse(source)
  assertContract(contract)
  const digest = createHash('sha256').update(source).digest('hex')
  checkOrWrite(options.goOutput, renderGo(contract, digest), options.check)
  checkOrWrite(options.tsOutput, renderTypeScript(contract, digest), options.check)
}

try {
  main()
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
}
