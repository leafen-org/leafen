import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const scriptsRoot = dirname(fileURLToPath(import.meta.url))
const productRoot = resolve(scriptsRoot, '..')

function parseArgs(argv) {
  const options = {
    check: false,
    contract: resolve(productRoot, 'contracts/workspace-export-wire.json'),
    goOutput: resolve(productRoot, 'internal/app/workspace_export_wire.generated.go'),
    tsOutput: resolve(productRoot, 'web/src/workspaceExportWire.generated.ts'),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') {
      options.check = true
      continue
    }
    const key = { '--contract': 'contract', '--go-output': 'goOutput', '--ts-output': 'tsOutput' }[argument]
    if (!key || !argv[index + 1]) throw new Error(`unknown or incomplete argument: ${argument}`)
    options[key] = resolve(productRoot, argv[index + 1])
    index += 1
  }
  return options
}

function assertContract(contract) {
  if (contract?.schemaVersion !== 2 || contract?.name !== 'workspace-export') {
    throw new Error('workspace export contract must use schemaVersion 2')
  }
  for (const key of ['bounds', 'constants', 'errors', 'enums', 'records']) {
    if (!Array.isArray(contract[key]) || contract[key].length === 0) throw new Error(`contract requires ${key}`)
  }
  const unique = (values, label) => {
    if (new Set(values).size !== values.length) throw new Error(`${label} contains duplicates`)
  }
  unique(contract.records.map((record) => record.goName), 'Go records')
  unique(contract.records.map((record) => record.tsName), 'TypeScript records')
  unique(contract.constants.map((constant) => constant.goName), 'Go constants')
  unique(contract.constants.map((constant) => constant.tsName), 'TypeScript constants')
  for (const record of contract.records) unique(record.fields.map((field) => field.jsonName), `${record.tsName} fields`)
}

function renderGo(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-workspace-export-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    'package app',
    '',
    'const (',
  ]
  for (const bound of contract.bounds) lines.push(`\t${bound.goName} = ${bound.value}`)
  for (const constant of contract.constants) lines.push(`\t${constant.goName} = ${JSON.stringify(constant.value)}`)
  lines.push('')
  for (const error of contract.errors) lines.push(`\t${error.goName} = ${JSON.stringify(error.value)}`)
  for (const enumeration of contract.enums) {
    lines.push('')
    for (const value of enumeration.values) lines.push(`\t${value.goName} = ${JSON.stringify(value.value)}`)
  }
  lines.push(')', '')
  for (const record of contract.records) {
    lines.push(`type ${record.goName} struct {`)
    for (const field of record.fields) lines.push(`\t${field.goName} ${field.goType} \`json:"${field.jsonName}"\``)
    lines.push('}', '')
  }
  const formatted = spawnSync('gofmt', [], { input: `${lines.join('\n')}\n`, encoding: 'utf8' })
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'gofmt failed')
  return formatted.stdout
}

function renderTypeScript(contract, digest) {
  const lines = [
    '// Code generated by scripts/generate-workspace-export-wire.mjs. DO NOT EDIT.',
    `// Contract SHA-256: ${digest}`,
    '',
    'export const workspaceExportBounds = {',
  ]
  for (const bound of contract.bounds) lines.push(`  ${bound.tsName}: ${bound.value},`)
  lines.push('} as const;', '', 'export const workspaceExportConstants = {')
  for (const constant of contract.constants) lines.push(`  ${constant.tsName}: ${JSON.stringify(constant.value)},`)
  lines.push('} as const;', '', 'export const workspaceExportErrorCodes = {')
  for (const error of contract.errors) lines.push(`  ${error.tsName}: ${JSON.stringify(error.value)},`)
  lines.push('} as const;', '')
  for (const enumeration of contract.enums) {
    lines.push(`export const ${enumeration.tsValuesName} = {`)
    for (const value of enumeration.values) lines.push(`  ${value.tsName}: ${JSON.stringify(value.value)},`)
    lines.push('} as const;')
    lines.push(`export type ${enumeration.tsName} = typeof ${enumeration.tsValuesName}[keyof typeof ${enumeration.tsValuesName}];`, '')
  }
  for (const record of contract.records) {
    lines.push(`export type ${record.tsName} = {`)
    for (const field of record.fields) lines.push(`  ${field.jsonName}: ${field.tsType};`)
    lines.push('};', '')
  }
  while (lines.at(-1) === '') lines.pop()
  return `${lines.join('\n')}\n`
}

function checkOrWrite(path, expected, check) {
  if (check) {
    let actual = ''
    try {
      actual = readFileSync(path, 'utf8')
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
    if (actual !== expected) {
      process.stderr.write(`stale generated output: ${relative(productRoot, path)}\n`)
      process.exitCode = 1
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, expected)
}

try {
  const options = parseArgs(process.argv.slice(2))
  const source = readFileSync(options.contract, 'utf8')
  const contract = JSON.parse(source)
  assertContract(contract)
  const digest = createHash('sha256').update(source).digest('hex')
  checkOrWrite(options.goOutput, renderGo(contract, digest), options.check)
  checkOrWrite(options.tsOutput, renderTypeScript(contract, digest), options.check)
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
}
